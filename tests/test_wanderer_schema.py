import sqlite3
import unittest
from unittest.mock import patch

from classroom_app.db import schema_wanderers
from classroom_app.db.schema_wanderers import ensure_wanderer_schema, wanderer_schema_statements
from tests.wanderer_test_support import WandererDbTestCase

WANDERER_TABLES = {
    "wanderer_agents", "wanderer_knowledge_entries", "wanderer_memory_threads",
    "wanderer_action_log", "wanderer_dao_reviews", "wanderer_runtime_settings",
    "wanderer_relationships", "wanderer_legacies", "wanderer_episodic_memories",
    "wanderer_memory_chapters", "wanderer_daily_reflections",
}
LIFECYCLE_COLUMNS = {
    "born_at", "lifespan_weeks", "life_penalty_weeks", "life_extensions", "talents_json",
    "last_extend_at", "last_appeal_at", "last_resurrect_at", "appeal_requested",
    "appeal_requested_at", "appeal_note", "legacy_id",
}
HUMANITY_COLUMNS = {
    "persona_version", "persona_source_hash", "persona_source_json", "persona_updated_at",
    "mood_json", "self_tuning_json", "last_reflection_at",
}


class WandererSchemaSqliteTest(WandererDbTestCase):
    seed_on_setup = False

    def test_init_database_creates_all_six_tables(self):
        with self.connect() as conn:
            names = {row[0] for row in conn.execute("SELECT name FROM sqlite_master WHERE type = 'table'")}
        self.assertTrue(WANDERER_TABLES <= names, WANDERER_TABLES - names)

    def test_ensure_is_idempotent(self):
        with self.connect() as conn, patch.object(schema_wanderers, "_SCHEMA_READY", False):
            ensure_wanderer_schema(conn, engine="sqlite")
            ensure_wanderer_schema(conn, engine="sqlite")
            self.assertTrue(schema_wanderers._SCHEMA_READY)

    def test_knowledge_unique_per_wanderer_and_source(self):
        with self.connect() as conn:
            insert = (
                "INSERT INTO wanderer_knowledge_entries (wanderer_id, source_kind, source_ref, digest, created_at, updated_at)"
                " VALUES (999, 'seed', 'x', 'd', '2026-10-25T00:00:00', '2026-10-25T00:00:00')"
            )
            conn.execute(insert)
            with self.assertRaises(sqlite3.IntegrityError):
                conn.execute(insert)
            conn.rollback()

    def test_indexes_exist(self):
        with self.connect() as conn:
            indexes = {row[0] for row in conn.execute("SELECT name FROM sqlite_master WHERE type = 'index'")}
        for name in ("idx_wanderer_action_log_wanderer", "idx_wanderer_action_log_created",
                     "idx_wanderer_dao_reviews_wanderer", "idx_wanderer_relationships_affinity",
                     "idx_wanderer_legacies_status", "idx_wanderer_episodes_status",
                     "idx_wanderer_episodes_importance", "idx_wanderer_chapters_period",
                     "idx_wanderer_reflections_date"):
            self.assertIn(name, indexes)

    def test_lifecycle_columns_exist(self):
        with self.connect() as conn:
            columns = {row[1] for row in conn.execute("PRAGMA table_info(wanderer_agents)")}
        self.assertTrue(LIFECYCLE_COLUMNS <= columns, LIFECYCLE_COLUMNS - columns)
        self.assertTrue(HUMANITY_COLUMNS <= columns, HUMANITY_COLUMNS - columns)

    def test_action_and_memory_locations_exist(self):
        with self.connect() as conn:
            action_columns = {row[1] for row in conn.execute("PRAGMA table_info(wanderer_action_log)")}
            memory_columns = {row[1] for row in conn.execute("PRAGMA table_info(wanderer_episodic_memories)")}
        self.assertIn("location", action_columns)
        self.assertIn("location", memory_columns)


class WandererSchemaDialectTest(unittest.TestCase):
    def test_postgres_ddl_uses_identity_not_autoincrement(self):
        ddl = "\n".join(wanderer_schema_statements("postgres"))
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY", ddl)
        self.assertNotIn("AUTOINCREMENT", ddl)
        for table in WANDERER_TABLES:
            self.assertIn(f"CREATE TABLE IF NOT EXISTS {table}", ddl)

    def test_sqlite_ddl_uses_autoincrement(self):
        ddl = "\n".join(wanderer_schema_statements("sqlite"))
        self.assertIn("AUTOINCREMENT", ddl)
        self.assertNotIn("IDENTITY", ddl)


if __name__ == "__main__":
    unittest.main()
