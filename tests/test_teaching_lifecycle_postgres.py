"""Opt-in native teaching lock races in an exclusively created loopback DB.

Real domain create/delete/relink SQL is exercised. The small fixture reuses
production root/assignment/document definitions; unrelated parent/lookup tables
contain only their required keys. It is not a full migration or HTTP rehearsal.
"""
