from tools.assessment_postgres_rehearsal import connect_offline


@unittest.skipUnless(os.environ.get('ASSESSMENT_REHEARSAL_TEST_CLUSTER'), 'Requires owned offline PG cluster')
class SocialAttentionPostgresTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.cluster = Path(os.environ['ASSESSMENT_REHEARSAL_TEST_CLUSTER'])
        cls.port = int(os.environ['ASSESSMENT_REHEARSAL_TEST_PORT'])
        cls.name = 'lanshare_assessment_rehearsal_attention_' + uuid.uuid4().hex[:10]
        cls.admin = connect_offline(cluster_dir=cls.cluster, port=cls.port, database='lanshare_assessment_rehearsal')
        cls.admin.autocommit = True
        cls.admin.execute(f'CREATE DATABASE "{cls.name}" TEMPLATE template0')

    @classmethod
    def tearDownClass(cls):
        try:
            cls.admin.execute(f'DROP DATABASE "{cls.name}"')
        finally:
            cls.admin.close()

    def connect(self):
        raw = connect_offline(cluster_dir=self.cluster, port=self.port, database=self.name)
        raw.row_factory = sqlite_compatible_dict_row
        return LanSharePostgresConnection(raw)

    def setUp(self):
        for target in ('classroom_app.db.connection.get_configured_db_engine',
                       'classroom_app.db.schema_social.get_configured_db_engine',
                       'classroom_app.services.message_center_service.get_configured_db_engine',
                       'classroom_app.services.email_notification_service.get_configured_db_engine',
                       'classroom_app.services.notification_delivery.get_configured_db_engine'):
            self.enterContext(patch(target, return_value='postgres'))
        self.enterContext(patch.object(schema_social, '_SCHEMA_READY', False))
        self.enterContext(patch.object(messages, '_wake_wanderers'))
        people = lambda conn, ids: {i: {'name': i, 'is_wanderer': False, 'tier_badge': None} for i in ids}
        self.enterContext(patch.object(conversations, 'load_people', side_effect=people))
        self.enterContext(patch('classroom_app.services.social_identity_service.load_people', side_effect=people))
        with self.connect() as conn:
            conn.execute('DROP SCHEMA public CASCADE; CREATE SCHEMA public')
            schema_social.ensure_social_schema(conn)
            conn.execute("""CREATE TABLE private_message_blocks(owner_identity TEXT, blocked_identity TEXT);
                CREATE TABLE user_notification_preferences(identity TEXT,event_key TEXT,enabled INTEGER,updated_at TEXT,
                    PRIMARY KEY(identity,event_key));
                CREATE TABLE students(id INTEGER PRIMARY KEY,name TEXT,email TEXT,enrollment_status TEXT);
                INSERT INTO students VALUES(1,'A','','active'),(2,'B','','active'),(3,'C','','active');
                CREATE TABLE message_center_notifications(
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    recipient_identity TEXT,recipient_role TEXT,recipient_user_pk INTEGER,category TEXT,severity TEXT,
                    actor_identity TEXT,actor_role TEXT,actor_user_pk INTEGER,actor_display_name TEXT,title TEXT,
                    body_preview TEXT,link_url TEXT,class_offering_id INTEGER,ref_type TEXT,ref_id TEXT,
                    metadata_json TEXT,created_at TEXT,read_at TEXT,email_status TEXT,email_job_id INTEGER,
                    email_queued_at TEXT,email_sent_at TEXT,aggregate_key TEXT,aggregate_count INTEGER DEFAULT 1,
                    ref_post_id INTEGER,target_state TEXT);
                INSERT INTO social_friendships(identity_a,identity_b,status,requester_identity,created_at)
                    VALUES('student:1','student:2','accepted','student:1','2026-10-27'),
                          ('student:2','student:3','accepted','student:2','2026-10-27');""")
            conn.commit()
            # Mirror startup's committed schema warm-up before workers accept
            # traffic; otherwise this fixture races DDL rather than messaging.
            schema_social.ensure_social_schema(conn)

    def send(self, index, *, nonce=None, mentions=True):
        with self.connect() as conn:
            try:
                result = messages.send_message(conn, {'role': 'student', 'id': 1}, 'dm:student:1|student:2',
                    {'body': f'Concurrent {index}', 'mentions': ['student:2'] if mentions else [],
                     'client_nonce': nonce or f'parallel-{index}'})
                conn.commit()
                return result['id']
            except SocialError as error:
                conn.rollback()
                return error.status_code

    def race(self, count, fn):
        barrier = threading.Barrier(count)
        def task(index):
            barrier.wait(timeout=10)
            return fn(index)
        with ThreadPoolExecutor(max_workers=count) as pool:
            return list(pool.map(task, range(count)))

    def test_six_parallel_mentions_only_commit_three(self):
        result = self.race(6, self.send)
        self.assertEqual(result.count(429), 3)
        with self.connect() as conn:
            self.assertEqual(conn.execute('SELECT COUNT(*) FROM social_messages').fetchone()[0], 3)
            self.assertEqual(conn.execute('SELECT value FROM social_daily_counters').fetchone()[0], 3)
            self.assertEqual(conn.execute('SELECT COUNT(*) FROM message_center_notifications').fetchone()[0], 3)

    def test_parallel_same_nonce_commits_one_message_and_quota(self):
        result = self.race(6, lambda i: self.send(i, nonce='same'))
        self.assertEqual(len(set(result)), 1)
        with self.connect() as conn:
            self.assertEqual(conn.execute('SELECT COUNT(*) FROM social_messages').fetchone()[0], 1)
            self.assertEqual(conn.execute('SELECT value FROM social_daily_counters').fetchone()[0], 1)

    def test_parallel_ordinary_messages_make_one_unread_card(self):
        self.race(6, lambda i: self.send(i, mentions=False))
        with self.connect() as conn:
            rows = conn.execute('SELECT aggregate_count FROM message_center_notifications').fetchall()
            self.assertEqual([r[0] for r in rows], [6])

    def test_read_waits_for_sends_and_keeps_newer_card_unread(self):
        first = self.send(1, mentions=False)
        self.send(2, mentions=False)
        with self.connect() as conn:
            messages.mark_read(conn, {'role': 'student', 'id': 2}, 'dm:student:1|student:2', first)
            conn.commit()
            self.assertIsNone(conn.execute('SELECT read_at FROM message_center_notifications').fetchone()[0])
