"""Opt-in behavior durability probe, restricted to the dedicated capacity rehearsal cluster."""
from __future__ import annotations

import argparse
from contextlib import contextmanager
from dataclasses import replace
import json
import os
from pathlib import Path
import sys
import tempfile
import threading
import time
import uuid
from unittest.mock import patch

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-disposable-capacity-cluster", action="store_true", required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    from tools.isolated_environment import guard_dotenv_loading, isolate_sqlite_environment
    from psycopg import connect, sql

    guard_dotenv_loading()
    with tempfile.TemporaryDirectory(prefix="behavior-pg-") as runtime:
        isolate_sqlite_environment(Path(runtime))
        os.environ.update(DB_ENGINE="postgres", POSTGRES_BACKEND_READY="true", POSTGRES_POOL_ENABLED="false",
                          DATABASE_URL="postgresql://rehearsal_admin@127.0.0.1:18766/lanshare_assessment_rehearsal_capacity",
                          SECRET_KEY="synthetic-behavior-probe-only")
        kwargs = dict(host="127.0.0.1", port=18766, dbname="lanshare_assessment_rehearsal_capacity",
                      user="rehearsal_admin", connect_timeout=3)
        schema = f"behavior_probe_{uuid.uuid4().hex}"
        with connect(**kwargs, autocommit=True) as admin:
            actual = Path(admin.execute("SHOW data_directory").fetchone()[0]).resolve()
            expected = (REPO / ".codex-temp/platform-capacity-20261105-pg").resolve()
            if actual != expected:
                raise RuntimeError("Refusing a PostgreSQL cluster outside the dedicated rehearsal directory")
            admin.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(schema)))
        from classroom_app.db.postgres import LanSharePostgresConnection, sqlite_compatible_dict_row
        from classroom_app.db.schema_behavior_inbox import ensure_behavior_inbox_schema
        from classroom_app.db.schema_cultivation_progress import ensure_cultivation_progress_schema
        from classroom_app.services import behavior_inbox_service as inbox
        from classroom_app.services import behavior_tracking_service as behavior
        from classroom_app.services.student_points_service import ensure_points_schema
        from classroom_app.services.student_streak_service import ensure_streak_schema
        from classroom_app.services.behavior_inbox_recovery_service import recover_behavior_receipt, BehaviorRecoveryOrderError

        fail_commit = threading.Event()

        class Connection(LanSharePostgresConnection):
            def commit(self):
                super().commit()
                if fail_commit.is_set():
                    fail_commit.clear()
                    raise ConnectionError("synthetic commit acknowledgment lost")

        @contextmanager
        def connection():
            raw = connect(**kwargs, row_factory=sqlite_compatible_dict_row)
            raw.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(schema)))
            raw.execute("SET statement_timeout = '3s'")
            raw.execute("SET lock_timeout = '1s'")
            raw.commit()
            with Connection(raw) as conn:
                yield conn

        checks = {}
        try:
            with connection() as conn:
                ensure_behavior_inbox_schema(conn, engine="postgres")
                conn.execute("CREATE TABLE class_offerings (id INTEGER PRIMARY KEY)")
                conn.execute("INSERT INTO class_offerings VALUES (910001)")
                conn.execute("CREATE TABLE students (id INTEGER PRIMARY KEY)")
                conn.execute("INSERT INTO students VALUES (920001)")
                # Structure only. Identity sequences are local to the cloned table.
                for name in ("classroom_behavior_events", "classroom_behavior_states"):
                    conn.raw_connection.execute(sql.SQL("CREATE TABLE {} (LIKE public.{} INCLUDING ALL)").format(
                        sql.Identifier(name), sql.Identifier(name)))
                identity = conn.execute("SELECT is_identity FROM information_schema.columns WHERE table_schema = ? "
                                        "AND table_name = 'classroom_behavior_events' AND column_name = 'id'", (schema,)).fetchone()
                if identity["is_identity"] != "YES":
                    conn.execute("ALTER TABLE classroom_behavior_events ALTER COLUMN id DROP DEFAULT")
                    conn.execute("ALTER TABLE classroom_behavior_events ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY")
                ensure_cultivation_progress_schema(conn, engine="postgres")
                ensure_streak_schema(conn)
                ensure_points_schema(conn)
                conn.commit()
            pipeline = inbox.BehaviorWritePipeline(behavior._record_behavior_batch_in_connection)
            request = inbox.BehaviorWriteRequest(910001, 920001, "student", "Synthetic", "classroom_discussion", [
                {"action_type": "page_click", "summary_text": "synthetic click", "payload": {}},
                {"action_type": "presence_heartbeat", "summary_text": "", "payload": {"focused": False, "visibility_state": "visible"}},
            ])
            lock_namespace = int(uuid.uuid4().hex[:7], 16)
            with patch.object(inbox, "get_db_connection", connection), patch.object(pipeline, "start"), patch.object(
                inbox, "CAPACITY_LOCK", (0x42505453, lock_namespace)
            ), patch.object(inbox, "APPLY_LOCK", (0x42505453, lock_namespace + 1)):
                fail_commit.set()
                accepted = pipeline.submit(request)
                assert accepted["accepted_event_count"] == 0 and accepted["durable_event_count"] == 2
                pipeline.submit(request)
                with connection() as conn:
                    assert conn.execute("SELECT COUNT(*) AS n FROM behavior_write_inbox").fetchone()["n"] == 1
                checks["intake_unknown_commit_and_same_id"] = True
                with connection() as conn:
                    before_upgrade = dict(conn.execute("SELECT * FROM behavior_write_inbox").fetchone())
                    conn.execute("ALTER TABLE behavior_write_inbox DROP COLUMN resolved_at")
                    conn.execute("ALTER TABLE behavior_write_inbox DROP CONSTRAINT behavior_write_inbox_state_check")
                    conn.execute("ALTER TABLE behavior_write_inbox ADD CONSTRAINT behavior_write_inbox_state_check "
                                 "CHECK(state IN ('pending','applied'))")
                    conn.commit()
                    ensure_behavior_inbox_schema(conn, engine="postgres")
                    assert dict(conn.execute("SELECT * FROM behavior_write_inbox").fetchone()) == before_upgrade
                    conn.execute("SAVEPOINT verify_state_upgrade")
                    for state in ("pending", "applied", "quarantined", "discarded"):
                        conn.execute("UPDATE behavior_write_inbox SET state=?", (state,))
                    try:
                        conn.execute("UPDATE behavior_write_inbox SET state='invalid_state'")
                        raise AssertionError("Unknown receipt state was accepted")
                    except Exception as exc:
                        assert getattr(exc, "sqlstate", "") == "23514"
                    conn.execute("ROLLBACK TO SAVEPOINT verify_state_upgrade")
                    conn.execute("RELEASE SAVEPOINT verify_state_upgrade")
                    conn.commit()
                checks["legacy_check_and_resolved_at_upgrade_preserve_original_receipt"] = True
                fail_commit.set()
                try:
                    pipeline._drain_once()
                except ConnectionError:
                    pass
                assert not pipeline._drain_once()
                receipt = pipeline.submit(request)
                assert receipt["write_mode"] == "synced" and receipt["accepted_event_count"] == 1
                with connection() as conn:
                    assert conn.execute("SELECT COUNT(*) AS n FROM classroom_behavior_events").fetchone()["n"] == 1
                    assert conn.execute("SELECT total_activity_count FROM classroom_behavior_states").fetchone()[0] == 1
                    assert conn.execute("SELECT COUNT(*) AS n FROM student_point_ledger").fetchone()["n"] == 1
                    assert conn.execute("SELECT dirty_version FROM learning_progress_snapshots").fetchone()[0] == 1
                checks["apply_unknown_commit_no_duplicate_event_points_or_dirty_version"] = True

                # Fail an actual PG statement after the entire scoring path, then retry the original batch.
                bad_request = replace(request, batch_id=inbox.new_batch_id())
                pipeline.submit(bad_request)
                original = pipeline._apply_batch

                def poison(conn, **values):
                    original(conn, **values)
                    conn.execute("SELECT 1 / 0")

                pipeline._apply_batch = poison
                assert pipeline._drain_once()
                with connection() as conn:
                    assert conn.execute("SELECT COUNT(*) AS n FROM classroom_behavior_events").fetchone()["n"] == 1
                    row = conn.execute("SELECT state, attempts FROM behavior_write_inbox WHERE batch_id = ?", (bad_request.batch_id,)).fetchone()
                    assert row["state"] == "pending" and row["attempts"] == 1
                    conn.execute("UPDATE behavior_write_inbox SET retry_at = NULL")
                    conn.commit()
                pipeline._apply_batch = original
                assert pipeline._drain_once()
                checks["postgres_failed_transaction_savepoint_rolls_back_all_effects_and_retries"] = True

                # Two independent claimant objects cannot apply the same batch twice.
                pipeline.submit(replace(request, batch_id=inbox.new_batch_id()))
                other = inbox.BehaviorWritePipeline(original)
                barrier = threading.Barrier(2)
                results = []

                def run(worker):
                    barrier.wait()
                    results.append(worker._drain_once())

                workers = [threading.Thread(target=run, args=(worker,)) for worker in (pipeline, other)]
                for thread in workers:
                    thread.start()
                for thread in workers:
                    thread.join(5)
                    assert not thread.is_alive()
                assert sum(results) == 1
                with connection() as conn:
                    assert conn.execute("SELECT COUNT(*) AS n FROM classroom_behavior_events").fetchone()["n"] == 3
                    assert conn.execute("SELECT COUNT(*) AS n FROM student_point_ledger").fetchone()["n"] == 1
                    assert conn.execute("SELECT dirty_version FROM learning_progress_snapshots").fetchone()[0] == 3
                checks["two_claimants_one_apply_and_daily_reward_once"] = True

                pipeline.submit(replace(request, batch_id=inbox.new_batch_id()))
                recovered = inbox.BehaviorWritePipeline(original)
                assert recovered._drain_once()
                checks["fresh_worker_replays_pending_receipt"] = True

                # Any subsequent business query remains valid after a rejected duplicate payload.
                with connection() as conn:
                    try:
                        pipeline.submit(replace(request, events=[]), conn=conn)
                    except inbox.BehaviorBatchConflict:
                        pass
                    assert conn.execute("SELECT 1 AS ok").fetchone()["ok"] == 1
                checks["caller_transaction_reusable_after_intake_conflict"] = True

                def quarantine_valid_batch():
                    failed = replace(request, batch_id=inbox.new_batch_id())
                    pipeline.submit(failed)
                    with connection() as conn:
                        saved = dict(conn.execute("SELECT * FROM behavior_write_inbox WHERE batch_id=?", (failed.batch_id,)).fetchone())
                        effects_before = conn.execute("SELECT COUNT(*) AS n FROM classroom_behavior_events").fetchone()["n"]
                        dirty_before = conn.execute("SELECT dirty_version FROM learning_progress_snapshots").fetchone()[0]
                    pipeline._apply_batch = poison
                    for index in range(3):
                        assert pipeline._drain_once()
                        with connection() as conn:
                            row = conn.execute("SELECT * FROM behavior_write_inbox WHERE batch_id=?", (failed.batch_id,)).fetchone()
                            assert row["state"] == ("quarantined" if index == 2 else "pending")
                            assert row["payload_hash"] == saved["payload_hash"] and row["events_json"] == saved["events_json"]
                            assert row["applied_at"] is None and row["resolved_at"] is None
                            assert conn.execute("SELECT COUNT(*) AS n FROM classroom_behavior_events").fetchone()["n"] == effects_before
                            assert conn.execute("SELECT dirty_version FROM learning_progress_snapshots").fetchone()[0] == dirty_before
                            assert conn.execute("SELECT COUNT(*) AS n FROM student_point_ledger").fetchone()["n"] == 1
                            conn.execute("UPDATE behavior_write_inbox SET retry_at=NULL WHERE batch_id=?", (failed.batch_id,))
                            conn.commit()
                    pipeline._apply_batch = original
                    assert pipeline.submit(failed)["write_mode"] == "quarantined"
                    return failed, saved

                failed, saved = quarantine_valid_batch()
                pipeline.submit(replace(request, batch_id=inbox.new_batch_id()))
                assert pipeline._drain_once()  # Same actor proceeds past Q.
                with connection() as conn:
                    before_late_retry = dict(conn.execute("SELECT * FROM behavior_write_inbox WHERE batch_key=?", (saved["batch_key"],)).fetchone())
                    try:
                        recover_behavior_receipt(conn, action="retry", batch_key=saved["batch_key"], payload_hash=saved["payload_hash"],
                            class_offering_id=request.class_offering_id, user_role="student", user_pk=request.user_pk,
                            operator="teacher:synthetic", reason="cannot replay past later committed activity")
                        raise AssertionError("Out-of-order recovery was accepted")
                    except BehaviorRecoveryOrderError:
                        pass
                    assert dict(conn.execute("SELECT * FROM behavior_write_inbox WHERE batch_key=?", (saved["batch_key"],)).fetchone()) == before_late_retry
                checks["late_admin_retry_refused_without_receipt_or_scoring_mutation"] = True
                with connection() as conn:
                    try:
                        inbox.prepare_behavior_deletion(conn, user_role="student", user_pk=request.user_pk)
                        raise AssertionError("Quarantine did not block actor deletion")
                    except inbox.BehaviorDeletionPending:
                        pass
                for changes in ({"payload_hash": "0" * 64}, {"user_pk": request.user_pk + 1}):
                    with connection() as conn:
                        values = dict(action="discard", batch_key=saved["batch_key"], payload_hash=saved["payload_hash"],
                            class_offering_id=request.class_offering_id, user_role="student", user_pk=request.user_pk,
                            operator="teacher:synthetic", reason="reviewed synthetic PG failure")
                        values.update(changes)
                        try:
                            recover_behavior_receipt(conn, **values)
                            raise AssertionError("Wrong recovery identity/hash accepted")
                        except inbox.BehaviorBatchConflict:
                            pass
                with connection() as conn:
                    recover_behavior_receipt(conn, action="discard", batch_key=saved["batch_key"], payload_hash=saved["payload_hash"],
                        class_offering_id=request.class_offering_id, user_role="student", user_pk=request.user_pk,
                        operator="teacher:synthetic", reason="reviewed synthetic PG failure")
                    conn.commit()
                    discarded = conn.execute("SELECT * FROM behavior_write_inbox WHERE batch_key=?", (saved["batch_key"],)).fetchone()
                    assert discarded["state"] == "discarded" and discarded["events_json"] == saved["events_json"]
                    assert discarded["applied_at"] is None and discarded["resolved_at"] is not None
                    assert json.loads(discarded["result_json"])["recovery_actions"][0]["action"] == "discard"
                assert pipeline.submit(failed)["write_mode"] == "discarded"
                checks["three_sql22_failures_quarantine_atomically_and_actor_continues"] = True
                checks["quarantine_scope_hash_discard_audit_and_delete_guard"] = True

                retry_request, saved = quarantine_valid_batch()
                with connection() as conn:
                    recover_behavior_receipt(conn, action="retry", batch_key=saved["batch_key"], payload_hash=saved["payload_hash"],
                        class_offering_id=request.class_offering_id, user_role="student", user_pk=request.user_pk,
                        operator="teacher:synthetic", reason="underlying synthetic failure repaired")
                    conn.commit()
                fail_commit.set()
                try:
                    pipeline._drain_once()
                except ConnectionError:
                    pass
                assert not pipeline._drain_once()
                assert pipeline.submit(retry_request)["write_mode"] == "synced"
                with connection() as conn:
                    row = conn.execute("SELECT * FROM behavior_write_inbox WHERE batch_key=?", (saved["batch_key"],)).fetchone()
                    assert row["state"] == "applied" and json.loads(row["result_json"])["recovery_actions"][0]["action"] == "retry"
                    assert conn.execute("SELECT COUNT(*) AS n FROM student_point_ledger").fetchone()["n"] == 1
                checks["explicit_retry_unknown_commit_stays_applied_without_duplicate_reward"] = True

                # An intake holding the actor parent lock commits before deletion
                # can check its newly accepted pending receipt.
                admitted = threading.Event()
                release_intake = threading.Event()
                deletion_started = threading.Event()
                deletion_finished = threading.Event()
                outcomes = []
                persist = pipeline._persist_in_connection

                def hold_intake(*values):
                    value = persist(*values)
                    admitted.set()
                    assert release_intake.wait(3)
                    return value

                def intake_first():
                    try:
                        pipeline.submit(replace(request, batch_id=inbox.new_batch_id()))
                        outcomes.append("admitted")
                    except Exception as exc:
                        outcomes.append(type(exc).__name__)

                def delete_second():
                    deletion_started.set()
                    try:
                        with connection() as conn:
                            inbox.prepare_behavior_deletion(conn, user_role="student", user_pk=request.user_pk)
                            conn.execute("DELETE FROM students WHERE id = ?", (request.user_pk,))
                        outcomes.append("deleted")
                    except inbox.BehaviorDeletionPending:
                        outcomes.append("pending_blocked")
                    finally:
                        deletion_finished.set()

                with patch.object(pipeline, "_persist_in_connection", side_effect=hold_intake):
                    one = threading.Thread(target=intake_first)
                    one.start()
                    assert admitted.wait(2)
                    two = threading.Thread(target=delete_second)
                    two.start()
                    assert deletion_started.wait(1)
                    assert not deletion_finished.wait(0.1)
                    release_intake.set()
                    one.join(3)
                    two.join(3)
                    assert not one.is_alive() and not two.is_alive()
                assert sorted(outcomes) == ["admitted", "pending_blocked"], outcomes
                assert pipeline._drain_once()
                checks["intake_parent_lock_makes_concurrent_actor_delete_see_pending"] = True

                # If deletion wins, an already authenticated late intake must be
                # rejected when its actor row disappears, before inbox acceptance.
                outcomes.clear()
                with connection() as conn:
                    inbox.prepare_behavior_deletion(conn, user_role="student", user_pk=request.user_pk)
                    conn.execute("DELETE FROM students WHERE id = ?", (request.user_pk,))
                    one = threading.Thread(target=intake_first)
                    one.start()
                    time.sleep(0.1)
                    assert one.is_alive()
                    conn.commit()
                    one.join(3)
                    assert not one.is_alive()
                assert outcomes == ["BehaviorBatchConflict"], outcomes
                with connection() as conn:
                    assert conn.execute("SELECT COUNT(*) AS n FROM behavior_write_inbox WHERE state='pending'").fetchone()["n"] == 0
                    assert conn.execute("SELECT COUNT(*) AS n FROM behavior_write_inbox WHERE display_name <> ''").fetchone()["n"] == 0
                checks["actor_delete_wins_rejects_late_intake_and_retires_applied_receipts"] = True
        finally:
            with connect(**kwargs, autocommit=True) as admin:
                admin.execute(sql.SQL("DROP SCHEMA {} CASCADE").format(sql.Identifier(schema)))
        report = {"status": "passed", "checks": checks, "postgres_port": 18766,
                  "isolation": "unique disposable schema, synthetic events only, no public writes"}
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(report, indent=2), encoding="utf-8")
        print(json.dumps(report))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
