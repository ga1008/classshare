"""Validate measured presence and count the union of credited time intervals."""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
import json

from .behavior_event_validation import is_measured_presence
from .behavior_inbox_service import CLIENT_RETRY_DAYS


HEARTBEAT_MAX_DELTA_SECONDS = 90
ACTIVE_PRESENCE_WINDOW_SECONDS = 150
MAX_FUTURE_SKEW_MS = 5000
MAX_INTERVAL_MS = HEARTBEAT_MAX_DELTA_SECONDS * 1000
MAX_SAMPLE_AGE_MS = CLIENT_RETRY_DAYS * 86400 * 1000
COVERAGE_WINDOW_MS = MAX_SAMPLE_AGE_MS + MAX_INTERVAL_MS
MAX_RANGES_PER_SIGNAL = 2048
SIGNALS = {"learning", "visible", "hidden", "blur", "lurk", "ai"}
REMAINDERS = SIGNALS | {"rolling_learning"}


def _epoch_ms(stamp: datetime) -> int:
    # Durable receipts and legacy login claims are generated by the same
    # server-local datetime clock. A timezone-aware value retains its offset.
    return int(stamp.timestamp() * 1000)


def timestamp_ms(value) -> int:
    if not value:
        return 0
    try:
        return _epoch_ms(datetime.fromisoformat(str(value)))
    except (ValueError, OverflowError, OSError):
        return 0


@dataclass(frozen=True)
class PresenceSample:
    received_ms: int
    observed_ms: int
    visibility: str
    focused: bool
    idle_seconds: int
    ai_open: bool
    interval: tuple[int, int] | None = None
    learning_end_ms: int = 0
    status_rank: int = 0


def read_presence_sample(payload: dict, received_at: datetime, session_started_at) -> PresenceSample | None:
    received = _epoch_ms(received_at)
    if not is_measured_presence(payload):
        return PresenceSample(received, received, "visible" if str(payload.get("visibility_state") or "visible") == "visible" else "hidden",
                              bool(payload.get("focused", True)), max(0, int(payload.get("idle_seconds") or 0)), False)

    visibility = payload.get("visibility_state")
    focused, idle = payload.get("focused"), payload.get("idle_seconds")
    observed = payload.get("presence_observed_ms", payload.get("interval_end_ms"))
    if (visibility not in ("visible", "hidden") or type(focused) is not bool or type(idle) is not int or idle < 0
            or type(observed) is not int or not received - MAX_SAMPLE_AGE_MS <= observed <= received + MAX_FUTURE_SKEW_MS):
        return None

    session = timestamp_ms(session_started_at)
    start, end = payload.get("interval_start_ms"), payload.get("interval_end_ms")
    interval, learning_end = None, 0
    if (session > 0 and type(start) is int and type(end) is int and end == observed
            and 0 < start < end and end - start <= MAX_INTERVAL_MS):
        start, end = max(start, session), min(end, received)
        if start < end:
            interval = start, end
            learning_end = min(end, observed - max(0, idle - ACTIVE_PRESENCE_WINDOW_SECONDS) * 1000)
    status_rank = 2 if "interval_start_ms" not in payload and "interval_end_ms" not in payload else 1
    return PresenceSample(received, min(observed, received), visibility, focused, idle,
                          payload.get("ai_panel_open") is True, interval, learning_end, status_rank)


def _load_coverage(raw: str) -> dict | None:
    """Fail closed if persisted coverage is corrupt; resetting it can recredit time."""
    try:
        data = json.loads(raw)
    except (ValueError, TypeError, RecursionError):
        return None
    if not isinstance(data, dict) or set(data) - {"reference", "observed", "status_rank", "cutoff", "ranges", "remainders"}:
        return None
    for key in ("reference", "observed", "cutoff"):
        value = data.setdefault(key, 0)
        if type(value) is not int or value < 0:
            return None
    status_rank = data.setdefault("status_rank", 0)
    if type(status_rank) is not int or not 0 <= status_rank <= 2:
        return None
    ranges, remainders = data.setdefault("ranges", {}), data.setdefault("remainders", {})
    if (not isinstance(ranges, dict) or set(ranges) - SIGNALS or not isinstance(remainders, dict)
            or set(remainders) - REMAINDERS or any(type(v) is not int or not 0 <= v < 1000 for v in remainders.values())):
        return None
    for entries in ranges.values():
        if not isinstance(entries, list) or len(entries) > MAX_RANGES_PER_SIGNAL:
            return None
        previous_end = 0
        for entry in entries:
            if (not isinstance(entry, list) or len(entry) != 2 or any(type(v) is not int for v in entry)
                    or not previous_end < entry[0] < entry[1] <= data["reference"]):
                return None
            previous_end = entry[1]
    return data


def _add_interval(ranges, start: int, end: int, rolling_start: int) -> tuple[list, int, int]:
    """Merge half-open intervals and return newly covered full and rolling milliseconds."""
    added, rolling_added = end - start, max(0, end - rolling_start)
    merged, left, right = [], start, end
    for old_start, old_end in ranges:
        added -= max(0, min(old_end, end) - max(old_start, start))
        rolling_added -= max(0, min(old_end, end) - max(old_start, rolling_start))
        if old_end < left:
            merged.append([old_start, old_end])
        elif right < old_start:
            merged.append([left, right])
            left, right = old_start, old_end
        else:
            left, right = min(left, old_start), max(right, old_end)
    merged.append([left, right])
    if len(merged) > MAX_RANGES_PER_SIGNAL:
        # Never forget still-replayable coverage to make room for a new range.
        return ranges, 0, 0
    return merged, added, rolling_added


def _whole_seconds(remainders: dict, key: str, added_ms: int) -> int:
    seconds, remainders[key] = divmod(remainders.get(key, 0) + added_ms, 1000)
    return seconds


def measure_presence(raw_coverage: str, sample: PresenceSample, *, session_since: int, rolling_since: int, page_key: str | None):
    coverage = _load_coverage(raw_coverage)
    if coverage is None:
        return None
    reference = max(coverage["reference"], sample.received_ms)
    coverage["reference"] = reference
    floor = reference - COVERAGE_WINDOW_MS
    ranges, remainders = coverage["ranges"], coverage["remainders"]
    for signal, entries in ranges.items():
        ranges[signal] = [[max(start, floor), end] for start, end in entries if end > floor]
    if coverage["cutoff"] != rolling_since:
        coverage["cutoff"] = rolling_since
        coverage["remainders"] = remainders = {"learning": remainders.get("learning", 0)}

    deltas = dict.fromkeys(REMAINDERS, 0)
    fresh_status = sample.observed_ms >= session_since and (
        sample.observed_ms, sample.status_rank
    ) > (coverage["observed"], coverage["status_rank"])
    if fresh_status:
        coverage["observed"] = sample.observed_ms
        coverage["status_rank"] = sample.status_rank
    if sample.interval is not None:
        start, end = sample.interval
        start = max(start, floor)
        if sample.visibility == "visible" and sample.focused and start < sample.learning_end_ms:
            ranges["learning"], added, rolling_added = _add_interval(ranges.get("learning", []), start,
                                                                     sample.learning_end_ms, max(start, rolling_since))
            deltas["learning"] = _whole_seconds(remainders, "learning", added)
            deltas["rolling_learning"] = _whole_seconds(remainders, "rolling_learning", rolling_added)

        start = max(start, rolling_since)
        if start < end:
            signals = [sample.visibility]
            if not sample.focused:
                signals.append("blur")
                if sample.visibility == "visible" and page_key == "classroom_discussion":
                    signals.append("lurk")
            if sample.ai_open:
                signals.append("ai")
            for signal in signals:
                ranges[signal], added, _ = _add_interval(ranges.get(signal, []), start, end, end)
                deltas[signal] = _whole_seconds(remainders, signal, added)
    return json.dumps(coverage, separators=(",", ":")), deltas, fresh_status
