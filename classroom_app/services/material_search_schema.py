"""Runtime tables for the material knowledge index (engine-aware, idempotent).

- ``material_search_documents``: one row per indexed ``course_materials`` file
  (what was indexed, from which ``file_hash`` / ``updated_at``, with which
  extractor version, and the outcome).
- ``material_search_chunks``: the searchable text of that file, cut into
  locator-sized pieces (a PDF page, a slide, a Markdown section, an HTML
  package lesson section, a worksheet). Each chunk carries a human label
  (``第 3 页``) and a ready-to-use deep link so a hit can be opened in place.

Kept out of ``classroom_app/db`` on purpose (AI/Agent standard §7): the index
is derived data, rebuilt at any time by the scheduler, so it never enters the
migration gate. ``ensure_material_search_schema`` is safe to call on every
operation: it is a no-op once the tables exist and re-checks the catalog so a
rolled-back DDL (or a swapped test database) is repaired on the next call.
"""
from __future__ import annotations

from typing import Any

from ..db.connection import get_configured_db_engine

_READY_ENGINES: set[str] = set()


def _identity_column(engine: str) -> str:
    if engine == "postgres":
        return "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    return "id INTEGER PRIMARY KEY AUTOINCREMENT"


def _tables_exist(conn: Any, engine: str) -> bool:
    if engine == "postgres":
        row = conn.execute(
            """
            SELECT COUNT(*) AS n FROM information_schema.tables
            WHERE table_schema = current_schema()
              AND table_name IN ('material_search_documents', 'material_search_chunks')
            """
        ).fetchone()
    else:
        row = conn.execute(
            """
            SELECT COUNT(*) AS n FROM sqlite_master
            WHERE type = 'table'
              AND name IN ('material_search_documents', 'material_search_chunks')
            """
        ).fetchone()
    if row is None:
        return False
    try:
        count = row["n"]
    except (TypeError, KeyError, IndexError):
        count = row[0]
    try:
        return int(count) >= 2
    except (TypeError, ValueError):
        return False


def ensure_material_search_schema(conn: Any) -> None:
    engine = get_configured_db_engine()
    if engine in _READY_ENGINES and _tables_exist(conn, engine):
        return
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS material_search_documents (
            material_id INTEGER PRIMARY KEY,
            teacher_id INTEGER NOT NULL DEFAULT 0,
            root_id INTEGER,
            file_hash TEXT NOT NULL DEFAULT '',
            source_updated_at TEXT NOT NULL DEFAULT '',
            extractor_version INTEGER NOT NULL DEFAULT 1,
            status TEXT NOT NULL DEFAULT 'ready',
            locator_kind TEXT NOT NULL DEFAULT '',
            kind TEXT NOT NULL DEFAULT '',
            chunk_count INTEGER NOT NULL DEFAULT 0,
            page_count INTEGER NOT NULL DEFAULT 0,
            char_count INTEGER NOT NULL DEFAULT 0,
            error_text TEXT NOT NULL DEFAULT '',
            indexed_at TEXT NOT NULL DEFAULT ''
        )
        """
    )
    conn.execute(
        f"""
        CREATE TABLE IF NOT EXISTS material_search_chunks (
            {_identity_column(engine)},
            material_id INTEGER NOT NULL,
            ordinal INTEGER NOT NULL DEFAULT 0,
            locator_kind TEXT NOT NULL DEFAULT '',
            locator_label TEXT NOT NULL DEFAULT '',
            locator_url TEXT NOT NULL DEFAULT '',
            page_number INTEGER NOT NULL DEFAULT 0,
            anchor TEXT NOT NULL DEFAULT '',
            heading TEXT NOT NULL DEFAULT '',
            text TEXT NOT NULL DEFAULT '',
            text_lower TEXT NOT NULL DEFAULT ''
        )
        """
    )
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_material_search_chunks_material "
        "ON material_search_chunks (material_id, ordinal)"
    )
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_material_search_documents_status "
        "ON material_search_documents (status, indexed_at)"
    )
    if engine == "postgres":
        _try_trigram_index(conn)
    _READY_ENGINES.add(engine)


def _try_trigram_index(conn: Any) -> None:
    """Best-effort pg_trgm GIN index so ``LIKE '%词%'`` on chunk text stops being a seq scan.

    Needs the extension (bundled with PostgreSQL contrib). Without privileges the
    statement fails; the search keeps working on a sequential scan, so the error
    is logged, not raised. Runs inside a savepoint so the caller's transaction
    stays usable on PostgreSQL.
    """
    from ..db.savepoint import best_effort

    with best_effort(conn, "material_search_trgm", log_prefix="[MATERIAL-INDEX]"):
        conn.execute("CREATE EXTENSION IF NOT EXISTS pg_trgm")
        conn.execute(
            "CREATE INDEX IF NOT EXISTS idx_material_search_chunks_text_trgm "
            "ON material_search_chunks USING gin (text_lower gin_trgm_ops)"
        )
