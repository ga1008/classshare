"""Per-student submission windows (个人补交通道, plan §3.4 / §6).

An approved 超时补交 appeal opens one ``assignment_student_windows`` row for
one student: the student may submit until ``due_at`` even though the
assignment itself no longer accepts submissions (it may even be ``closed``).
The window carries its own late-penalty policy; the submission stores a
late-policy snapshot built from it, so grading applies the penalty through the
existing ``apply_late_policy_to_score`` path.

Only students without a real submission use a window (nothing submitted, or
just an absence placeholder). A real submission is corrected through the
错误提交 appeal instead.

The table is engine-aware and ensured lazily (like the approval workflow
tables). Timestamps are local ISO-8601 TEXT, matching the assignment columns.
"""
from __future__ import annotations

import json
import math
from datetime import datetime, timedelta
from typing import Any, Mapping

from ..db.connection import execute_insert_returning_id, get_configured_db_engine
from .late_submission_policy import dt_to_iso, parse_iso_like_datetime

_SCHEMA_READY = False

WINDOW_KIND_LATE_APPEAL = "late_appeal"
WINDOW_KIND_TEACHER_EXTENSION = "teacher_extension"  # reserved (plan §6.8)
STATUS_ACTIVE = "active"
STATUS_USED = "used"
STATUS_EXPIRED = "expired"
STATUS_REVOKED = "revoked"

PENALTY_INHERIT = "inherit"
PENALTY_CUSTOM = "custom"
PENALTY_NONE = "none"
PENALTY_MODES = (PENALTY_INHERIT, PENALTY_CUSTOM, PENALTY_NONE)
INTERVAL_UNITS = {"day": 86400, "hour": 3600, "minute": 60, "second": 1}
UNIT_LABELS = {"day": "天", "hour": "小时", "minute": "分钟", "second": "秒"}
LATENESS_BASES = ("original_due", "window_open")

TASK_KIND_WINDOW_EXPIRY = "late_window_expiry"
TASK_KIND_WINDOW_REMINDER = "late_window_reminder"
REMINDER_BEFORE = timedelta(hours=1)


def ensure_student_window_schema(conn: Any) -> None:
    global _SCHEMA_READY
    if _SCHEMA_READY:
        return
    engine = get_configured_db_engine()
    id_column = ("id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if engine == "postgres"
                 else "id INTEGER PRIMARY KEY AUTOINCREMENT")
    conn.execute(
        f"""
        CREATE TABLE IF NOT EXISTS assignment_student_windows (
            {id_column},
            assignment_id TEXT NOT NULL,
            student_pk_id INTEGER NOT NULL,
            kind TEXT NOT NULL DEFAULT '{WINDOW_KIND_LATE_APPEAL}',
            source_request_id INTEGER,
            grant_no INTEGER NOT NULL DEFAULT 1,
            opens_at TEXT NOT NULL,
            due_at TEXT NOT NULL,
            duration_seconds INTEGER,
            penalty_mode TEXT NOT NULL DEFAULT '{PENALTY_INHERIT}',
            penalty_policy_json TEXT NOT NULL DEFAULT '{{}}',
            status TEXT NOT NULL DEFAULT '{STATUS_ACTIVE}',
            used_submission_id INTEGER,
            used_at TEXT,
            meta_json TEXT NOT NULL DEFAULT '{{}}',
            created_by_teacher_id INTEGER,
            revoked_reason TEXT NOT NULL DEFAULT '',
            created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
            updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
        """
    )
    conn.execute(
        "CREATE UNIQUE INDEX IF NOT EXISTS uq_assignment_student_windows_active "
        "ON assignment_student_windows (assignment_id, student_pk_id) WHERE status = 'active'"
    )
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_assignment_student_windows_lookup "
        "ON assignment_student_windows (assignment_id, student_pk_id, status)"
    )
    _SCHEMA_READY = True


def _read(conn, sql: str, params: tuple, *, many: bool = False):
    """Read the window table, re-ensuring it once if this database lacks it.

    These reads sit on hot submit/draft/page paths; a process-wide "schema
    ready" flag can be stale for a freshly attached database (as with the
    approval tables, see ``assessment_appeal_service._query_with_schema_retry``).
    """
    global _SCHEMA_READY
    ensure_student_window_schema(conn)
    try:
        cursor = conn.execute(sql, params)
    except Exception as exc:  # noqa: BLE001
        # PostgreSQL creates the table at startup and an error there aborts the
        # transaction, so only SQLite (tests swapping databases) retries.
        if "assignment_student_windows" not in str(exc) or get_configured_db_engine() == "postgres":
            raise
        _SCHEMA_READY = False
        ensure_student_window_schema(conn)
        cursor = conn.execute(sql, params)
    return cursor.fetchall() if many else cursor.fetchone()


def _now() -> datetime:
    return datetime.now().replace(microsecond=0)


def _number(raw: Any) -> float | None:
    try:
        value = float(raw)
    except (TypeError, ValueError):
        return None
    return value if math.isfinite(value) else None


# ---------------------------------------------------------------- penalty policy
def normalize_penalty_policy(raw: Mapping[str, Any] | None) -> dict[str, Any]:
    """Teacher form / stored JSON → the canonical window policy (plan §6.4)."""
    data = dict(raw or {})
    strategy = str(data.get("strategy") or "fixed").strip().lower()
    if strategy not in {"fixed", "gradient", "none"}:
        raise ValueError("扣分方式只能是一次性扣分、按时间梯度扣分或不扣分")
    points = _number(data.get("points")) or 0.0
    if not 0 <= points <= 100:
        raise ValueError("每次扣分需在 0-100 之间")
    unit = str(data.get("interval_unit") or "hour").strip().lower()
    if unit not in INTERVAL_UNITS:
        raise ValueError("扣分间隔单位只能是天、小时、分钟或秒")
    seconds = _number(data.get("interval_seconds"))
    if seconds is None:
        value = _number(data.get("interval_value"))
        seconds = (value or 1) * INTERVAL_UNITS[unit]
    if strategy == "gradient" and seconds < 1:
        raise ValueError("扣分间隔至少 1 秒")
    min_score = _number(data.get("min_score")) or 0.0
    cap = _number(data.get("score_cap"))
    max_penalty = _number(data.get("max_penalty_points"))
    for label, value in (("最低分", min_score), ("得分上限", cap), ("扣分封顶", max_penalty)):
        if value is not None and not 0 <= value <= 100:
            raise ValueError(f"{label}需在 0-100 之间")
    base = str(data.get("lateness_base") or "original_due").strip().lower()
    if base not in LATENESS_BASES:
        base = "original_due"
    return {
        "strategy": strategy, "points": points, "interval_seconds": int(max(1, seconds)), "interval_unit": unit,
        "lateness_base": base, "min_score": min_score, "score_cap": cap, "max_penalty_points": max_penalty,
    }


def assignment_penalty_policy(assignment: Mapping[str, Any]) -> dict[str, Any] | None:
    """The assignment's own late rule in window form, or None when it has none."""
    if not int(assignment.get("late_submission_enabled") or 0):
        return None
    hours = _number(assignment.get("late_penalty_interval_hours")) or 1
    return normalize_penalty_policy({
        "strategy": str(assignment.get("late_penalty_strategy") or "fixed"),
        "points": assignment.get("late_penalty_points") or 0,
        "interval_seconds": max(1, int(round(hours * 3600))),
        "interval_unit": "hour",
        "lateness_base": "original_due",
        "min_score": assignment.get("late_penalty_min_score") or 0,
        "score_cap": assignment.get("late_score_cap"),
    })


def resolve_window_policy(assignment: Mapping[str, Any], mode: str, custom: Mapping[str, Any] | None) -> dict[str, Any]:
    if mode == PENALTY_NONE:
        return normalize_penalty_policy({"strategy": "none"})
    if mode == PENALTY_INHERIT:
        inherited = assignment_penalty_policy(assignment)
        if inherited is None:
            raise ValueError("该作业没有设置补交扣分规则，请选择“新规则”或“不扣分”")
        return inherited
    return normalize_penalty_policy(custom)


def describe_penalty_policy(policy: Mapping[str, Any]) -> str:
    strategy = policy.get("strategy")
    if strategy == "none":
        return "不扣分"
    points = float(policy.get("points") or 0)
    if strategy == "gradient":
        unit = str(policy.get("interval_unit") or "hour")
        seconds = int(policy.get("interval_seconds") or 3600)
        step = seconds / INTERVAL_UNITS.get(unit, 1)
        text = f"每 {step:g} {UNIT_LABELS.get(unit, '小时')}扣 {points:g} 分"
        text += "，从补交通道开启起算" if policy.get("lateness_base") == "window_open" else "，从原截止时间起算"
    else:
        text = f"一次性扣 {points:g} 分"
    if policy.get("max_penalty_points") is not None:
        text += f"，最多扣 {float(policy['max_penalty_points']):g} 分"
    if float(policy.get("min_score") or 0):
        text += f"，最低 {float(policy['min_score']):g} 分"
    if policy.get("score_cap") is not None:
        text += f"，补交最高 {float(policy['score_cap']):g} 分"
    return text


def window_late_snapshot(assignment: Mapping[str, Any], window: Mapping[str, Any], submitted_at: Any) -> dict[str, Any]:
    """Late-policy snapshot for a submission made through a personal window.

    Same keys as ``build_late_submission_snapshot`` plus the window facts, so
    ``apply_late_policy_to_score`` handles it; ``none`` keeps the late flag
    for statistics but deducts nothing.
    """
    policy = json.loads(window.get("penalty_policy_json") or "{}") or {}
    submitted_dt = parse_iso_like_datetime(submitted_at) or _now()
    due_dt = parse_iso_like_datetime(assignment.get("due_at"))
    opens_dt = parse_iso_like_datetime(window.get("opens_at"))
    base_dt = opens_dt if policy.get("lateness_base") == "window_open" or due_dt is None else due_dt
    late_by = max(0, int((submitted_dt - base_dt).total_seconds())) if base_dt else 0
    interval_seconds = int(policy.get("interval_seconds") or 3600)
    return {
        "enabled": True,
        "is_late_submission": True,
        "submitted_at": dt_to_iso(submitted_dt),
        "due_at": dt_to_iso(due_dt),
        "late_by_seconds": late_by,
        "late_submission_until": window.get("due_at"),
        "late_penalty_strategy": policy.get("strategy") or "none",
        "late_penalty_interval_hours": interval_seconds / 3600,
        "late_penalty_interval_seconds": interval_seconds,
        "late_penalty_points": float(policy.get("points") or 0),
        "late_penalty_min_score": float(policy.get("min_score") or 0),
        "late_score_cap": policy.get("score_cap"),
        "late_penalty_max_points": policy.get("max_penalty_points"),
        "lateness_base": policy.get("lateness_base") or "original_due",
        "window_id": int(window["id"]),
        "grant_no": int(window.get("grant_no") or 1),
        "appeal_request_id": window.get("source_request_id"),
        "source": "personal_window",
    }


# ---------------------------------------------------------------- windows
def active_window(conn, assignment_id: Any, student_pk_id: Any, *, now: datetime | None = None) -> dict[str, Any] | None:
    """The student's open window (status active and not past due)."""
    row = _read(
        conn, "SELECT * FROM assignment_student_windows WHERE assignment_id = ? AND student_pk_id = ? AND status = ? LIMIT 1",
        (str(assignment_id), int(student_pk_id), STATUS_ACTIVE),
    )
    if not row:
        return None
    window = dict(row)
    due_dt = parse_iso_like_datetime(window.get("due_at"))
    if due_dt is None or (now or _now()) >= due_dt.replace(tzinfo=None):
        return None
    return window


def active_window_student_ids(conn, assignment_id: Any) -> set[int]:
    rows = _read(
        conn, "SELECT student_pk_id FROM assignment_student_windows WHERE assignment_id = ? AND status = ? AND due_at > ?",
        (str(assignment_id), STATUS_ACTIVE, dt_to_iso(_now())), many=True,
    )
    return {int(row["student_pk_id"]) for row in rows}


def count_windows(conn, assignment_id: Any, student_pk_id: Any, kind: str = WINDOW_KIND_LATE_APPEAL) -> int:
    row = _read(
        conn, "SELECT COUNT(*) AS n FROM assignment_student_windows WHERE assignment_id = ? AND student_pk_id = ? AND kind = ?",
        (str(assignment_id), int(student_pk_id), kind),
    )
    return int(row["n"] or 0)


def open_window(conn, *, assignment: Mapping[str, Any], student_pk_id: int, due_at: datetime, penalty_mode: str,
                policy: Mapping[str, Any], source_request_id: int | None, teacher_id: int | None,
                duration_seconds: int | None = None) -> dict[str, Any]:
    """Insert an active window and schedule its reminder and expiry (caller commits)."""
    from .scheduled_task_service import schedule_task

    ensure_student_window_schema(conn)
    now = _now()
    if due_at <= now:
        raise ValueError("补交截止时间必须晚于现在")
    if active_window(conn, assignment["id"], student_pk_id, now=now):
        raise ValueError("该生已有一个开放中的补交通道")
    # A stale "active" row past its due date would block the partial unique index.
    conn.execute(
        "UPDATE assignment_student_windows SET status = ?, updated_at = ? WHERE assignment_id = ? AND student_pk_id = ? AND status = ?",
        (STATUS_EXPIRED, dt_to_iso(now), str(assignment["id"]), int(student_pk_id), STATUS_ACTIVE),
    )
    grant_no = count_windows(conn, assignment["id"], student_pk_id) + 1
    window_id = execute_insert_returning_id(
        conn,
        """
        INSERT INTO assignment_student_windows (
            assignment_id, student_pk_id, kind, source_request_id, grant_no, opens_at, due_at, duration_seconds,
            penalty_mode, penalty_policy_json, status, created_by_teacher_id, created_at, updated_at
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """,
        (str(assignment["id"]), int(student_pk_id), WINDOW_KIND_LATE_APPEAL, source_request_id, grant_no,
         dt_to_iso(now), dt_to_iso(due_at), duration_seconds, penalty_mode,
         json.dumps(dict(policy), ensure_ascii=False), STATUS_ACTIVE, teacher_id, dt_to_iso(now), dt_to_iso(now)),
        engine=get_configured_db_engine(),
    )
    payload = {"window_id": int(window_id)}
    schedule_task(conn, task_kind=TASK_KIND_WINDOW_EXPIRY, run_at=due_at, payload=payload,
                  dedupe_key=f"late-window-expiry:{int(window_id)}", title="Close a personal late-submission window",
                  priority=80, max_attempts=3, replace=True)
    if due_at - now >= REMINDER_BEFORE * 2:
        schedule_task(conn, task_kind=TASK_KIND_WINDOW_REMINDER, run_at=due_at - REMINDER_BEFORE, payload=payload,
                      dedupe_key=f"late-window-reminder:{int(window_id)}", title="Remind a student before the window closes",
                      priority=120, max_attempts=2, replace=True)
    row = conn.execute("SELECT * FROM assignment_student_windows WHERE id = ?", (int(window_id),)).fetchone()
    return dict(row)


def mark_window_used(conn, window_id: int, submission_id: int) -> None:
    """Record the submission on its window, even if expiry raced ahead of the commit."""
    now = dt_to_iso(_now())
    conn.execute(
        "UPDATE assignment_student_windows SET status = ?, used_submission_id = ?, used_at = ?, updated_at = ? "
        "WHERE id = ? AND status IN (?, ?)",
        (STATUS_USED, int(submission_id), now, now, int(window_id), STATUS_ACTIVE, STATUS_EXPIRED),
    )


def student_window_view(window: Mapping[str, Any] | None) -> dict[str, Any] | None:
    """What the student page shows about an open window (own data only)."""
    if not window:
        return None
    policy = json.loads(window.get("penalty_policy_json") or "{}") or {}
    return {
        "id": int(window["id"]),
        "grant_no": int(window.get("grant_no") or 1),
        "opens_at": window.get("opens_at"),
        "due_at": window.get("due_at"),
        "penalty_label": describe_penalty_policy(policy) if policy else "不扣分",
    }


# ---------------------------------------------------------------- scheduled tasks
def _load_window(conn, window_id: Any) -> dict[str, Any] | None:
    row = _read(conn, "SELECT * FROM assignment_student_windows WHERE id = ? LIMIT 1", (int(window_id or 0),))
    return dict(row) if row else None


def _notify_window(conn, window: Mapping[str, Any], *, student_body: str, teacher_body: str | None, title: str,
                   ref: str) -> None:
    from . import message_center_service as mc

    assignment = conn.execute(
        "SELECT a.id, a.title, a.class_offering_id, o.teacher_id FROM assignments a "
        "LEFT JOIN class_offerings o ON o.id = a.class_offering_id WHERE a.id = ? LIMIT 1",
        (str(window["assignment_id"]),),
    ).fetchone()
    if not assignment:
        return
    recipients = [("student", int(window["student_pk_id"]), student_body)]
    if teacher_body and assignment["teacher_id"]:
        recipients.append(("teacher", int(assignment["teacher_id"]), teacher_body))
    for role, user_pk, body in recipients:
        mc._insert_notification_if_allowed(conn, mc._build_notification_payload(
            recipient_role=role, recipient_user_pk=user_pk, category=mc.MESSAGE_CATEGORY_APPROVAL,
            title=f"{title}：{assignment['title'] or '作业'}", severity="normal", body_preview=body,
            link_url=f"/assignment/{assignment['id']}", class_offering_id=mc._safe_int(assignment["class_offering_id"]),
            ref_type=f"late_window_{ref}", ref_id=f"{int(window['id'])}:{ref}",
        ))


def expire_window(conn, window_id: Any, *, now: datetime | None = None) -> str:
    window = _load_window(conn, window_id)
    if not window or window["status"] != STATUS_ACTIVE:
        return "noop"
    due_dt = parse_iso_like_datetime(window.get("due_at"))
    current = now or _now()
    if due_dt is not None and current < due_dt.replace(tzinfo=None):
        return "not_due"
    submitted = conn.execute(
        "SELECT id FROM submissions WHERE assignment_id = ? AND student_pk_id = ? AND COALESCE(is_absence_score, 0) = 0 "
        "AND status <> 'unsubmitted' LIMIT 1",
        (str(window["assignment_id"]), int(window["student_pk_id"])),
    ).fetchone()
    if submitted:
        # The student handed in (possibly via a reopened deadline): spent, not missed.
        mark_window_used(conn, int(window["id"]), int(submitted["id"]))
        return "used"
    conn.execute("UPDATE assignment_student_windows SET status = ?, updated_at = ? WHERE id = ? AND status = ?",
                 (STATUS_EXPIRED, dt_to_iso(current), int(window["id"]), STATUS_ACTIVE))
    student = conn.execute("SELECT name FROM students WHERE id = ?", (int(window["student_pk_id"]),)).fetchone()
    _notify_window(
        conn, window, title="补交通道已关闭", ref="expired",
        student_body="补交通道已到截止时间，你没有在期限内提交。",
        teacher_body=(f"{(student['name'] if student else '') or '学生'} 的补交通道已到期且未提交；"
                      "如课堂已结课，可在结课收尾中为其补记缺交。"),
    )
    return "expired"


def remind_window(conn, window_id: Any) -> str:
    window = _load_window(conn, window_id)
    if not window or window["status"] != STATUS_ACTIVE:
        return "noop"
    due = str(window.get("due_at") or "").replace("T", " ")[:16]
    _notify_window(conn, window, title="补交通道即将关闭", ref="reminder", teacher_body=None,
                   student_body=f"你的补交通道将在 {due} 关闭，请尽快完成并提交。")
    return "reminded"


def _run_task(task: Mapping[str, Any], action) -> str:
    from ..database import get_db_connection
    from ..db.connection import begin_immediate_transaction

    payload = task.get("payload") if isinstance(task.get("payload"), dict) else {}
    with get_db_connection() as conn:
        begin_immediate_transaction(conn)
        outcome = action(conn, payload.get("window_id"))
        conn.commit()
    return outcome


def handle_window_expiry_task(task: Mapping[str, Any]) -> str:
    return _run_task(task, expire_window)


def handle_window_reminder_task(task: Mapping[str, Any]) -> str:
    return _run_task(task, remind_window)
