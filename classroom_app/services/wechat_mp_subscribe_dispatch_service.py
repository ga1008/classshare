def claim_subscribe_report(conn: Any, *, report_id: str, user_role: str, user_pk: int) -> bool:
    """同一 report_id 只记一次授权（客户端重试/重复上报不虚增额度）。"""
    ensure_mp_subscribe_task_schema(conn)
    return _insert_ignore(
        conn,
        "mp_subscribe_reports",
        ("report_id", "user_role", "user_pk", "created_at"),
        "report_id",
        (report_id, user_role, int(user_pk), _iso(_now())),
    )


def load_subscribe_balances(conn: Any, *, user_role: str, user_pk: int) -> dict[str, int]:
    ensure_mp_subscribe_task_schema(conn)
    rows = conn.execute(
        "SELECT template_key, remaining FROM mp_subscribe_grants WHERE user_role = ? AND user_pk = ?",
        (user_role, int(user_pk)),
    ).fetchall()
    balances = {key: 0 for key in TEMPLATES}
    for row in rows:
        if row["template_key"] in balances:
            balances[row["template_key"]] = max(0, int(row["remaining"] or 0))
    return balances


