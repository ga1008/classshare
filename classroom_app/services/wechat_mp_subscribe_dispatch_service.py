def _default_transport(token: str, body: dict[str, Any]) -> dict[str, Any]:
    try:
        response = httpx.post(f"{_SUBSCRIBE_SEND_URL}?access_token={token}", json=body, timeout=8.0)
    except (httpx.ConnectError, httpx.ConnectTimeout) as exc:
        raise SendNotAttempted(type(exc).__name__) from None
    except httpx.HTTPError as exc:
        # 读/写超时等：请求可能已被处理。异常文本含带 token 的 URL，绝不外泄。
        raise SendOutcomeUnknown(type(exc).__name__) from None
    try:
        return response.json()
    except ValueError:
        raise SendOutcomeUnknown(f"non-json http {response.status_code}") from None


def _default_token_provider(force_refresh: bool) -> str:
    return _get_access_token(force_refresh=force_refresh)


def _claim(limit: int, worker: str, now: datetime) -> list[dict[str, Any]]:
    now_text = _iso(now)
    lease_until = _iso(now + timedelta(seconds=LEASE_SECONDS))
    with get_db_connection() as conn:
        ensure_mp_subscribe_task_schema(conn)
        if get_configured_db_engine() == "postgres":
            rows = conn.execute(
                """
                UPDATE mp_subscribe_tasks
                SET state = ?, lease_owner = ?, lease_until = ?, updated_at = ?
                WHERE id IN (
                    SELECT id FROM mp_subscribe_tasks
                    WHERE (state = ? AND next_attempt_at <= ?)
                       OR (state = ? AND lease_until <= ?)
                    ORDER BY next_attempt_at ASC, id ASC
                    LIMIT ?
                    FOR UPDATE SKIP LOCKED
                )
                RETURNING *
                """,
                (STATE_PROCESSING, worker, lease_until, now_text,
                 STATE_PENDING, now_text, STATE_PROCESSING, now_text, limit),
            ).fetchall()
            conn.commit()
            return [dict(row) for row in rows]
        candidates = conn.execute(
            """
            SELECT id FROM mp_subscribe_tasks
            WHERE (state = ? AND next_attempt_at <= ?)
               OR (state = ? AND lease_until <= ?)
            ORDER BY next_attempt_at ASC, id ASC
            LIMIT ?
            """,
            (STATE_PENDING, now_text, STATE_PROCESSING, now_text, limit),
        ).fetchall()
        claimed = []
        for row in candidates:
            cursor = conn.execute(
                """
                UPDATE mp_subscribe_tasks
                SET state = ?, lease_owner = ?, lease_until = ?, updated_at = ?
                WHERE id = ? AND ((state = ? AND next_attempt_at <= ?) OR (state = ? AND lease_until <= ?))
                """,
                (STATE_PROCESSING, worker, lease_until, now_text, int(row["id"]),
                 STATE_PENDING, now_text, STATE_PROCESSING, now_text),
            )
            if cursor.rowcount:
                claimed.append(int(row["id"]))
        conn.commit()
        if not claimed:
            return []
        placeholders = ", ".join("?" for _ in claimed)
        return [
            dict(row)
            for row in conn.execute(
                f"SELECT * FROM mp_subscribe_tasks WHERE id IN ({placeholders}) ORDER BY id", claimed
            ).fetchall()
        ]


def _warn_if_lease_lost(cursor: Any, task: dict[str, Any], state: str) -> None:
    """租约已被他人接管（本 worker 停顿超过 LEASE_SECONDS）：结果写不回去，
    另一 worker 可能已重发。只在日志里留痕，供运维核对是否出现重复推送。"""
    if not cursor.rowcount:
        print(f"[MP_SUBSCRIBE] task {task['id']} lease lost before recording {state}; possible duplicate send")


def _finish(conn: Any, task: dict[str, Any], worker: str, state: str, error: str = "") -> None:
    now_text = _iso(_now())
    cursor = conn.execute(
        """
        UPDATE mp_subscribe_tasks
        SET state = ?, last_error = ?, lease_owner = NULL, lease_until = NULL,
            attempts = attempts + 1, updated_at = ?, finished_at = ?
        WHERE id = ? AND state = ? AND lease_owner = ?
        """,
        (state, error[:200] or None, now_text, now_text, int(task["id"]), STATE_PROCESSING, worker),
    )
    _warn_if_lease_lost(cursor, task, state)


def _retry_or_fail(conn: Any, task: dict[str, Any], worker: str, error: str) -> str:
    attempts = int(task.get("attempts") or 0) + 1
    if attempts >= MAX_ATTEMPTS:
        _finish(conn, task, worker, STATE_FAILED, error)
        return STATE_FAILED
    now = _now()
    delay = RETRY_BASE_SECONDS * (2 ** (attempts - 1))
    cursor = conn.execute(
        """
        UPDATE mp_subscribe_tasks
        SET state = ?, attempts = ?, next_attempt_at = ?, last_error = ?,
            lease_owner = NULL, lease_until = NULL, updated_at = ?
        WHERE id = ? AND state = ? AND lease_owner = ?
        """,
        (STATE_PENDING, attempts, _iso(now + timedelta(seconds=delay)), error[:200],
         _iso(now), int(task["id"]), STATE_PROCESSING, worker),
    )
    _warn_if_lease_lost(cursor, task, STATE_PENDING)
    return STATE_PENDING


def _reserve_grant(conn: Any, task: dict[str, Any]) -> bool:
    cursor = conn.execute(
        """
        UPDATE mp_subscribe_grants SET remaining = remaining - 1, updated_at = ?
        WHERE user_role = ? AND user_pk = ? AND template_key = ? AND remaining > 0
        """,
        (_iso(_now()), task["user_role"], int(task["user_pk"]), task["template_key"]),
    )
    return bool(cursor.rowcount)


def _refund_grant(conn: Any, task: dict[str, Any]) -> None:
    conn.execute(
        """
        UPDATE mp_subscribe_grants SET remaining = remaining + 1, updated_at = ?
        WHERE user_role = ? AND user_pk = ? AND template_key = ?
        """,
        (_iso(_now()), task["user_role"], int(task["user_pk"]), task["template_key"]),
    )


def _send(task: dict[str, Any], openid: str, transport: Transport, token_provider: TokenProvider) -> tuple[str, str]:
    """事务外调用微信。返回 (结果, 错误说明)；结果为终态或 "retry"。"""
    template = TEMPLATES[task["template_key"]]
    body = {
        "touser": openid,
        "template_id": template["template_id"],
        "page": task["page"],
        "data": {field: {"value": value} for field, value in json.loads(task["values_json"]).items()},
    }
    try:
        token = token_provider(False)
        if not token:
            return "retry", "no_token"
        payload = transport(token, body)
        errcode = int(payload.get("errcode") or 0)
        if errcode in TOKEN_ERRCODES:
            token = token_provider(True)
            if not token:
                return "retry", "no_token"
            payload = transport(token, body)
            errcode = int(payload.get("errcode") or 0)
    except SendNotAttempted as exc:
        return "retry", f"not sent: {exc}"
    except SendOutcomeUnknown as exc:
        return STATE_UNKNOWN, f"unknown: {exc}"
    except Exception as exc:  # 防御：任何意外都不能让任务永远卡在 processing
        return STATE_UNKNOWN, f"unexpected: {type(exc).__name__}"
    if errcode == 0:
        return STATE_SUCCEEDED, ""
    if errcode == REJECTED_ERRCODE:
        return STATE_REJECTED, f"errcode {errcode}"
    if errcode in TEMPORARY_ERRCODES or errcode in TOKEN_ERRCODES:
        return "retry", f"errcode {errcode}"
    return STATE_FAILED, f"errcode {errcode} {str(payload.get('errmsg') or '')[:80]}"


def _process_one(
    task: dict[str, Any], worker: str, transport: Transport, token_provider: TokenProvider, now: datetime
) -> str:
    expires_at = str(task.get("expires_at") or "")
    with get_db_connection() as conn:
        if expires_at and expires_at <= _iso(now):
            _finish(conn, task, worker, STATE_EXPIRED)
            conn.commit()
            return STATE_EXPIRED
        openid = _find_openid(conn, task["user_role"], int(task["user_pk"]))
        if not openid:
            _finish(conn, task, worker, STATE_NO_BINDING)
            conn.commit()
            return STATE_NO_BINDING
        if not _reserve_grant(conn, task):
            _finish(conn, task, worker, STATE_NO_GRANT)
            conn.commit()
            return STATE_NO_GRANT
        conn.commit()

    state, error = _send(task, openid, transport, token_provider)

    with get_db_connection() as conn:
        if state == STATE_REJECTED:
            _clear_grants(conn, task["user_role"], int(task["user_pk"]), task["template_key"])
            _finish(conn, task, worker, state, error)
        elif state in (STATE_SUCCEEDED, STATE_UNKNOWN):
            _finish(conn, task, worker, state, error)
        elif state == STATE_FAILED:
            _refund_grant(conn, task)
            _finish(conn, task, worker, state, error)
        else:
            _refund_grant(conn, task)
            state = _retry_or_fail(conn, task, worker, error)
        conn.commit()
    if error:
        print(f"[MP_SUBSCRIBE] task {task['id']} {task['template_key']} -> {state} ({error})")
    return state


def dispatch_subscribe_tasks(
    *,
    transport: Optional[Transport] = None,
    token_provider: Optional[TokenProvider] = None,
    batch_size: int = DISPATCH_BATCH_SIZE,
    time_budget_seconds: float = DISPATCH_TIME_BUDGET_SECONDS,
    clock: Callable[[], datetime] = _now,
) -> dict[str, int]:
    """领取到期任务并发送，直到队列空或用完时间预算。返回各结果计数。"""
    worker = f"{os.getenv('SCHEDULER_WORKER_ID') or socket.gethostname()}:{uuid.uuid4().hex[:12]}"
    send = transport or _default_transport
    tokens = token_provider or _default_token_provider
    started = clock()
    stats: dict[str, int] = {}
    while (clock() - started).total_seconds() < time_budget_seconds:
        now = clock()
        batch = _claim(max(1, int(batch_size)), worker, now)
        if not batch:
            break
        for task in batch:
            state = _process_one(task, worker, send, tokens, now)
            stats[state] = stats.get(state, 0) + 1
    return stats


def ensure_dispatch_task(conn: Any) -> int:
    from .scheduled_task_service import schedule_task

    ensure_mp_subscribe_task_schema(conn)
    return schedule_task(
        conn,
        task_kind=DISPATCH_TASK_KIND,
        run_at=_now() + timedelta(seconds=30),
        payload={},
        dedupe_key="mp:subscribe-dispatch",
        recurrence_seconds=DISPATCH_INTERVAL_SECONDS,
        title="MP subscribe message dispatch",
        priority=70,
        max_attempts=3,
        replace=False,
    )
