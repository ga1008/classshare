def summarize_group(conn: Any, group_key: str) -> dict[str, Any]:
    ensure_mp_subscribe_task_schema(conn)
    rows = conn.execute(
        """
        SELECT state, COUNT(*) AS total, MAX(updated_at) AS last_update
        FROM mp_subscribe_tasks WHERE group_key = ?
        GROUP BY state
        """,
        (group_key,),
    ).fetchall()
    counts = {str(row["state"]): int(row["total"]) for row in rows}
    return {
        "group_key": group_key,
        "total": sum(counts.values()),
        "delivered": counts.get(STATE_SUCCEEDED, 0),
        "in_flight": counts.get(STATE_PENDING, 0) + counts.get(STATE_PROCESSING, 0),
        "no_grant": counts.get(STATE_NO_GRANT, 0) + counts.get(STATE_REJECTED, 0),
        "no_binding": counts.get(STATE_NO_BINDING, 0),
        "unknown": counts.get(STATE_UNKNOWN, 0),
        "failed": counts.get(STATE_FAILED, 0) + counts.get(STATE_EXPIRED, 0),
        "by_state": counts,
        "last_update": max((str(row["last_update"] or "") for row in rows), default=""),
    }


