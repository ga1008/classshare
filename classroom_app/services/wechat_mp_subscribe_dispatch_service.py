def _insert_ignore(conn: Any, table: str, columns: tuple[str, ...], conflict_column: str, params: tuple) -> bool:
    """按引擎 insert-ignore，``?`` 占位走连接门面的 qmark 转换，返回是否插入。

    不能用 ``db.sql`` 里的 insert-ignore 生成器：它的 postgres 输出是 ``$n`` 占位，
    运行时连接门面执行会报 "0 placeholders"。批次 B 之前的去重占位正是因此在生产
    PostgreSQL 上每次抛错、被吞掉后返回"已发过"，订阅消息从未真正发出。
    """
    column_sql = ", ".join(columns)
    values_sql = ", ".join("?" for _ in columns)
    if get_configured_db_engine() == "postgres":
        sql = f"INSERT INTO {table} ({column_sql}) VALUES ({values_sql}) ON CONFLICT ({conflict_column}) DO NOTHING"
    else:
        sql = f"INSERT OR IGNORE INTO {table} ({column_sql}) VALUES ({values_sql})"
    return bool(conn.execute(sql, params).rowcount)


def _has_grant(conn: Any, user_role: str, user_pk: int, template_key: str) -> bool:
    row = conn.execute(
        """
        SELECT remaining FROM mp_subscribe_grants
        WHERE user_role = ? AND user_pk = ? AND template_key = ?
        """,
        (user_role, int(user_pk), template_key),
    ).fetchone()
    return bool(row) and int(row["remaining"] or 0) > 0


def enqueue_subscribe_message(
    conn: Any,
    *,
    event_key: str,
    user_role: str,
    user_pk: int,
    template_key: str,
    values: dict[str, str],
    page: str = "pages/home/index",
    group_key: str = "",
    expires_at: Optional[str] = None,
) -> str:
    """登记一条待发订阅消息，返回 queued / no_binding / no_grant / rearmed / duplicate。

    无绑定/无额度的直接记为对应终态（worker 不必再处理）；同一事件
    再次入队时，若先前停在可唤醒终态且原因已消除，则重新排队。
    """
    if template_key not in TEMPLATES:
        raise ValueError(f"unknown subscribe template: {template_key}")
    ensure_mp_subscribe_task_schema(conn)
    now = _iso(_now())
    if not _find_openid(conn, user_role, user_pk):
        initial = STATE_NO_BINDING
    elif not _has_grant(conn, user_role, user_pk, template_key):
        initial = STATE_NO_GRANT
    else:
        initial = STATE_PENDING
    values_json = json.dumps(values, ensure_ascii=False, sort_keys=True)
    inserted = _insert_ignore(
        conn,
        "mp_subscribe_tasks",
        (
            "event_key", "group_key", "template_key", "user_role", "user_pk", "values_json",
            "page", "state", "attempts", "next_attempt_at", "expires_at", "created_at",
            "updated_at", "finished_at",
        ),
        "event_key",
        (
            event_key, group_key, template_key, user_role, int(user_pk), values_json,
            page, initial, 0, now, expires_at, now, now,
            None if initial == STATE_PENDING else now,
        ),
    )
    if inserted:
        return "queued" if initial == STATE_PENDING else initial
    if initial != STATE_PENDING:
        return initial
    placeholders = ", ".join("?" for _ in REARMABLE_STATES)
    rearmed = conn.execute(
        f"""
        UPDATE mp_subscribe_tasks
        SET state = ?, attempts = 0, next_attempt_at = ?, values_json = ?, page = ?,
            expires_at = ?, last_error = NULL, finished_at = NULL, updated_at = ?
        WHERE event_key = ? AND state IN ({placeholders})
        """,
        (STATE_PENDING, now, values_json, page, expires_at, now, event_key, *REARMABLE_STATES),
    )
    return "rearmed" if rearmed.rowcount else "duplicate"


def graded_event_key(submission_id: Any, score: Any, feedback_md: Any) -> str:
    """同一份提交的同一批改结果只推一次；分数或评语变化才再推。"""
    digest = hashlib.sha256(
        json.dumps([str(score), str(feedback_md or "")], ensure_ascii=False).encode("utf-8")
    ).hexdigest()[:16]
    return f"graded:{submission_id}:{digest}"


def nudge_group_key(assignment_id: Any, day: Optional[str] = None) -> str:
    return f"nudge:{assignment_id}:{day or _now().date().isoformat()}"


