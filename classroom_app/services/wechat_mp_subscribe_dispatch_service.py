"""小程序订阅消息：持久化发送任务 + scheduler 发送 worker（批次 B / C07、C08）。

业务侧（截止扫描、批改完成、教师催交）只在自己的短事务里 ``enqueue``
一行任务，绝不在请求/批改事务内调用微信。scheduler 容器里的
``dispatch_subscribe_tasks`` 原子领取任务后在事务外发送。

状态机（``mp_subscribe_tasks.state``）::

    pending → processing → succeeded
                         → no_binding / no_grant / rejected   （可被同事件重新入队唤醒）
                         → expired                            （截止提醒过了截止时间）
                         → unknown                            （已发出但结果未知，不重发）
                         → failed                             （确定失败或重试耗尽）
    processing → pending（暂时失败，指数退避）

额度语义：领取时原子预扣一次授权（``remaining > 0``），只有"确定没送达"
才退还；结果未知按已用处理（微信侧大概率已扣）。同一用户同一模板只剩
一次授权时，两条任务不可能同时拿到额度。
"""

from __future__ import annotations

import hashlib
import json
import os
import socket
import uuid
from datetime import datetime, timedelta
from typing import Any, Callable, Optional

import httpx

from ..db.connection import get_configured_db_engine, get_db_connection
from .wechat_mp_subscribe_service import (
    TEMPLATES,
    _SUBSCRIBE_SEND_URL,
    _clear_grants,
    _find_openid,
    _get_access_token,
    ensure_mp_subscribe_schema,
)

DISPATCH_TASK_KIND = "mp_subscribe_dispatch"
DISPATCH_INTERVAL_SECONDS = 30
DISPATCH_BATCH_SIZE = 10
DISPATCH_TIME_BUDGET_SECONDS = 40
LEASE_SECONDS = 300
MAX_ATTEMPTS = 4
RETRY_BASE_SECONDS = 60

STATE_PENDING = "pending"
STATE_PROCESSING = "processing"
STATE_SUCCEEDED = "succeeded"
STATE_NO_BINDING = "no_binding"
STATE_NO_GRANT = "no_grant"
STATE_REJECTED = "rejected"
STATE_EXPIRED = "expired"
STATE_UNKNOWN = "unknown"
STATE_FAILED = "failed"

# 同一事件再次入队时可被唤醒的终态：原因可能已消除（用户新授权/新绑定）。
REARMABLE_STATES = (STATE_NO_BINDING, STATE_NO_GRANT, STATE_REJECTED)
# 微信"系统繁忙/频率"类错误码：退还额度后按退避重试。
TEMPORARY_ERRCODES = frozenset({-1, 45009, 45011})
TOKEN_ERRCODES = frozenset({40001, 42001})
REJECTED_ERRCODE = 43101

_SCHEMA_READY = False

Transport = Callable[[str, dict[str, Any]], dict[str, Any]]
TokenProvider = Callable[[bool], str]


class SendNotAttempted(Exception):
    """请求未离开本机（连接失败等），可安全重试且额度应退还。"""


class SendOutcomeUnknown(Exception):
    """请求可能已到达微信（读超时等），不得重发。"""


def _now() -> datetime:
    return datetime.now()


def _iso(value: datetime) -> str:
    return value.isoformat(timespec="seconds")


def ensure_mp_subscribe_task_schema(conn: Any) -> None:
    """任务表 + 授权上报幂等表（engine-aware、幂等，不进 REQUIRED 集）。"""
    global _SCHEMA_READY
    if _SCHEMA_READY:
        return
    ensure_mp_subscribe_schema(conn)
    engine = get_configured_db_engine()
    id_column = (
        "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        if engine == "postgres"
        else "id INTEGER PRIMARY KEY AUTOINCREMENT"
    )
    conn.execute(
        f"""
        CREATE TABLE IF NOT EXISTS mp_subscribe_tasks (
            {id_column},
            event_key TEXT NOT NULL UNIQUE,
            group_key TEXT NOT NULL DEFAULT '',
            template_key TEXT NOT NULL,
            user_role TEXT NOT NULL,
            user_pk INTEGER NOT NULL,
            values_json TEXT NOT NULL,
            page TEXT NOT NULL,
            state TEXT NOT NULL,
            attempts INTEGER NOT NULL DEFAULT 0,
            next_attempt_at TEXT NOT NULL,
            expires_at TEXT,
            lease_owner TEXT,
            lease_until TEXT,
            last_error TEXT,
            created_at TEXT NOT NULL,
            updated_at TEXT NOT NULL,
            finished_at TEXT
        )
        """
    )
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_mp_subscribe_tasks_due "
        "ON mp_subscribe_tasks (state, next_attempt_at)"
    )
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_mp_subscribe_tasks_group "
        "ON mp_subscribe_tasks (group_key)"
    )
    conn.execute(
        f"""
        CREATE TABLE IF NOT EXISTS mp_subscribe_reports (
            {id_column},
            report_id TEXT NOT NULL UNIQUE,
            user_role TEXT NOT NULL,
            user_pk INTEGER NOT NULL,
            created_at TEXT NOT NULL
        )
        """
    )
    _SCHEMA_READY = True


def reset_task_schema_ready_for_tests() -> None:
    global _SCHEMA_READY
    _SCHEMA_READY = False


