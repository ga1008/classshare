DEADLINE_SCAN_TASK_KIND = "mp_deadline_reminder_scan"
DEADLINE_SCAN_INTERVAL_SECONDS = 1800


def run_deadline_reminder_scan(conn: Any) -> dict[str, int]:
    """扫描 24h 内截止的作业，给未提交且有额度的学生推截止提醒。

    合班课堂口径：学生属于 offering 的主班或 class_offering_class_links
    任一挂链班级即计入。dedupe = 作业×学生×档位，天然幂等。
    """
    from .offering_membership_service import offering_student_where

    ensure_mp_subscribe_schema(conn)
    now = datetime.now()
    rows = conn.execute(
        f"""
        SELECT a.id AS assignment_id, a.title, a.due_at,
               s.id AS student_id, cl.name AS class_name
        FROM assignments a
        JOIN class_offerings o ON o.id = a.class_offering_id
        JOIN students s ON {offering_student_where()}
        JOIN classes cl ON cl.id = s.class_id
        WHERE a.status = 'published'
          AND a.due_at IS NOT NULL AND a.due_at != ''
          AND COALESCE(s.enrollment_status, 'active') = 'active'
          AND NOT EXISTS (
              SELECT 1 FROM submissions sub
              WHERE sub.assignment_id = a.id
                AND sub.student_pk_id = s.id
                AND COALESCE(sub.is_absence_score, 0) = 0
          )
          AND NOT EXISTS (
              SELECT 1 FROM learning_stage_exam_attempts lsea
              WHERE lsea.assignment_id = a.id
          )
        """,
    ).fetchall()

    stats = {"candidates": 0, "sent": 0, "no_grant": 0, "skipped": 0}
    for row in rows:
        item = dict(row)
        due_text = str(item.get("due_at") or "").replace("T", " ")
        try:
            due_at = datetime.fromisoformat(due_text)
        except ValueError:
            continue
        remaining = (due_at - now).total_seconds()
        stage = deadline_stage(remaining)
        if stage is None:
            continue
        stats["candidates"] += 1
        hours_left = max(1, int(remaining // 3600))
        status = send_subscribe_message(
            conn,
            user_role="student",
            user_pk=int(item["student_id"]),
            template_key="deadline",
            values=build_deadline_values(item["title"], item["class_name"], due_text, hours_left),
            page="pages/tasks/index",
            dedupe_key=f"deadline:{item['assignment_id']}:{item['student_id']}:{stage}",
        )
        if status == "sent":
            stats["sent"] += 1
        elif status == "no_grant":
            stats["no_grant"] += 1
        else:
            stats["skipped"] += 1
    return stats


def ensure_deadline_scan_task(conn: Any) -> int:
    from datetime import timedelta

    from .scheduled_task_service import schedule_task

    return schedule_task(
        conn,
        task_kind=DEADLINE_SCAN_TASK_KIND,
        run_at=datetime.now() + timedelta(seconds=120),
        payload={},
        dedupe_key="mp:deadline-reminder-scan",
        recurrence_seconds=DEADLINE_SCAN_INTERVAL_SECONDS,
        title="MP assignment deadline reminder scan",
        priority=80,
        max_attempts=3,
        replace=False,
    )
