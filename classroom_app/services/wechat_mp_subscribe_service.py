def build_graded_values(assignment_title: Any, score: Any, feedback_preview: Any) -> dict[str, str]:
    """作业批改完成通知：thing6 标题 / number7 评分 / phrase3 结果 / thing4 备注。"""
    return {
        "thing6": clamp_thing(assignment_title),
        "number7": clamp_number(score),
        "phrase3": clamp_phrase("已批改"),
        "thing4": clamp_thing(feedback_preview or "点击查看批改详情"),
    }


def build_deadline_values(
    assignment_title: Any, class_name: Any, due_at: Any, hours_left: int
) -> dict[str, str]:
    """班级作业提醒：thing10 标题 / thing11 班级 / date8 截止 / thing3 提醒。"""
    if hours_left <= 2:
        tip = "即将截止，请尽快提交"
    else:
        tip = f"距截止约{hours_left}小时，别忘了提交"
    return {
        "thing10": clamp_thing(assignment_title),
        "thing11": clamp_thing(class_name),
        "date8": format_wechat_datetime(due_at),
        "thing3": clamp_thing(tip),
    }


def build_nudge_values(assignment_title: Any, course_name: Any, due_at: Any) -> dict[str, str]:
    """作业催交通知：thing1 标题 / thing4 科目 / time2 截止 / thing3 备注。"""
    return {
        "thing1": clamp_thing(assignment_title),
        "thing4": clamp_thing(course_name),
        "time2": format_wechat_datetime(due_at),
        "thing3": clamp_thing("老师提醒：请尽快提交作业"),
    }


def deadline_stage(remaining_seconds: float) -> Optional[str]:
    """截止扫描分档：≤2h → stage2；≤24h → stage24；其余不提醒。"""
    if remaining_seconds <= 0:
        return None
    hours = remaining_seconds / 3600
    if hours <= 2:
        return "stage2"
    if hours <= 24:
        return "stage24"
    return None


