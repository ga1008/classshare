# access_token 与发送
# ---------------------------------------------------------------------------

def _get_access_token(force_refresh: bool = False) -> str:
    """stable_token（多进程各自缓存互不失效）。失败返回空串。"""
    with _TOKEN_LOCK:
        if not force_refresh and _TOKEN_CACHE["token"] and time.time() < _TOKEN_CACHE["expires_at"]:
            return str(_TOKEN_CACHE["token"])
        appid, secret = get_wechat_mp_credentials()
        if not appid or not secret:
            print("[MP_SUBSCRIBE] 缺少小程序凭据，跳过发送")
            return ""
        try:
            response = httpx.post(
                _STABLE_TOKEN_URL,
                json={
                    "grant_type": "client_credential",
                    "appid": appid,
                    "secret": secret,
                    **({"force_refresh": True} if force_refresh else {}),
                },
                timeout=8.0,
            )
            payload = response.json()
        except Exception as exc:
            print(f"[MP_SUBSCRIBE] stable_token 请求失败: {exc}")
            return ""
        token = str(payload.get("access_token") or "")
        if not token:
            print(f"[MP_SUBSCRIBE] stable_token 错误: {payload.get('errcode')} {payload.get('errmsg')}")
            return ""
        expires_in = int(payload.get("expires_in") or 7200)
        _TOKEN_CACHE["token"] = token
        _TOKEN_CACHE["expires_at"] = time.time() + max(60, expires_in - 300)
        return token


def _find_openid(conn: Any, user_role: str, user_pk: int) -> str:
    row = conn.execute(
        """
        SELECT openid FROM wechat_bindings
        WHERE user_role = ? AND user_pk = ? AND status = 'active'
        ORDER BY id DESC LIMIT 1
        """,
        (user_role, int(user_pk)),
    ).fetchone()
    return str(row["openid"]) if row else ""


def send_subscribe_message(
    conn: Any,
    *,
    user_role: str,
    user_pk: int,
    template_key: str,
    values: dict[str, str],
    page: str = "pages/home/index",
    dedupe_key: Optional[str] = None,
) -> str:
    """发送一条订阅消息。返回状态：sent / no_grant / no_binding /
    duplicate / no_token / rejected / failed。永不抛异常。"""
    try:
        ensure_mp_subscribe_schema(conn)
        template = TEMPLATES.get(template_key)
        if not template:
            return "failed"
        if dedupe_key and not _claim_dedupe(
            conn,
            template_key=template_key,
            user_role=user_role,
            user_pk=user_pk,
            dedupe_key=dedupe_key,
        ):
            return "duplicate"
        openid = _find_openid(conn, user_role, user_pk)
        if not openid:
            return "no_binding"
        if not _consume_grant(conn, user_role, user_pk, template_key):
            return "no_grant"
        token = _get_access_token()
        if not token:
            return "no_token"

        body = {
            "touser": openid,
            "template_id": template["template_id"],
            "page": page,
            "data": {field: {"value": value} for field, value in values.items()},
        }
        payload: dict[str, Any] = {}
        for attempt in range(2):
            try:
                response = httpx.post(
                    f"{_SUBSCRIBE_SEND_URL}?access_token={token}",
                    json=body,
                    timeout=8.0,
                )
                payload = response.json()
            except Exception as exc:
                print(f"[MP_SUBSCRIBE] send 请求失败: {exc}")
                return "failed"
            errcode = int(payload.get("errcode") or 0)
            if errcode in (40001, 42001) and attempt == 0:
                token = _get_access_token(force_refresh=True)
                if not token:
                    return "no_token"
                continue
            break

        errcode = int(payload.get("errcode") or 0)
        if errcode == 0:
            return "sent"
        if errcode == 43101:
            # 用户拒收/取消订阅：清空余额，避免持续无效尝试
            _clear_grants(conn, user_role, user_pk, template_key)
            return "rejected"
        print(f"[MP_SUBSCRIBE] send 错误 template={template_key}: {errcode} {payload.get('errmsg')}")
        return "failed"
    except Exception as exc:
        print(f"[MP_SUBSCRIBE] send_subscribe_message 异常: {exc}")
        return "failed"


