_SCHEMA_READY = False
_TOKEN_LOCK = threading.Lock()
_TOKEN_CACHE: dict[str, Any] = {"token": "", "expires_at": 0.0}


def _now_iso() -> str:
    return datetime.now().isoformat(timespec="seconds")


def ensure_mp_subscribe_schema(conn: Any) -> None:
    """两张 runtime 表（engine-aware、幂等，不进 REQUIRED 集）。"""
    global _SCHEMA_READY
    if _SCHEMA_READY:
        return
    engine = get_configured_db_engine()
    id_column = (
        "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        if engine == "postgres"
        else "id INTEGER PRIMARY KEY AUTOINCREMENT"
    )
    conn.execute(
        f"""
        CREATE TABLE IF NOT EXISTS mp_subscribe_grants (
            {id_column},
            user_role TEXT NOT NULL,
            user_pk INTEGER NOT NULL,
            template_key TEXT NOT NULL,
            remaining INTEGER NOT NULL DEFAULT 0,
            updated_at TEXT NOT NULL,
            UNIQUE (user_role, user_pk, template_key)
        )
        """
    )
    conn.execute(
        f"""
        CREATE TABLE IF NOT EXISTS mp_subscribe_sends (
            {id_column},
            template_key TEXT NOT NULL,
            user_role TEXT NOT NULL,
            user_pk INTEGER NOT NULL,
            dedupe_key TEXT NOT NULL UNIQUE,
            sent_at TEXT NOT NULL
        )
        """
    )
    _SCHEMA_READY = True


def reset_schema_ready_for_tests() -> None:
    global _SCHEMA_READY
    _SCHEMA_READY = False


# ---------------------------------------------------------------------------
# 字段清洗：微信对每类字段有硬性长度/格式限制，超限整条发送失败。
# ---------------------------------------------------------------------------

def clamp_thing(value: Any, limit: int = 20) -> str:
    """thing.DATA：≤20 字符，超长截断加省略号；空值给占位符。"""
    text = str(value or "").strip().replace("\n", " ")
    if not text:
        return "—"
    if len(text) <= limit:
        return text
    return text[: limit - 1] + "…"


def clamp_phrase(value: Any) -> str:
    """phrase.DATA：≤5 字符的短语。"""
    text = str(value or "").strip()
    return (text[:5] or "已完成") if text else "已完成"


def clamp_number(value: Any) -> str:
    """number.DATA：纯数字字符串。"""
    try:
        number = float(value)
    except (TypeError, ValueError):
        return "0"
    return str(int(number)) if number == int(number) else f"{number:g}"


def format_wechat_datetime(value: Any) -> str:
    """date/time.DATA 接受 "2026年9月1日 23:59" 式格式。"""
    text = str(value or "").strip().replace("T", " ")
    try:
        parsed = datetime.fromisoformat(text)
    except ValueError:
        return text or "—"
    return f"{parsed.year}年{parsed.month}月{parsed.day}日 {parsed.hour:02d}:{parsed.minute:02d}"


# ---------------------------------------------------------------------------
# 授权额度台账
# ---------------------------------------------------------------------------

def record_subscribe_grants(
    conn: Any, *, user_role: str, user_pk: int, template_keys: list[str]
) -> dict[str, int]:
    """前端上报用户点了"允许"的模板，各自额度 +1。返回各 key 的最新余额。"""
    ensure_mp_subscribe_schema(conn)
    result: dict[str, int] = {}
    now = _now_iso()
    for key in template_keys:
        normalized = str(key or "").strip()
        if normalized not in TEMPLATES:
            continue
        row = conn.execute(
            """
            SELECT id, remaining FROM mp_subscribe_grants
            WHERE user_role = ? AND user_pk = ? AND template_key = ?
            """,
            (user_role, int(user_pk), normalized),
        ).fetchone()
        if row:
            remaining = int(row["remaining"]) + 1
            conn.execute(
                "UPDATE mp_subscribe_grants SET remaining = ?, updated_at = ? WHERE id = ?",
                (remaining, now, int(row["id"])),
            )
        else:
            remaining = 1
            conn.execute(
                """
                INSERT INTO mp_subscribe_grants (user_role, user_pk, template_key, remaining, updated_at)
                VALUES (?, ?, ?, ?, ?)
                """,
                (user_role, int(user_pk), normalized, remaining, now),
            )
        result[normalized] = remaining
    return result


def _consume_grant(conn: Any, user_role: str, user_pk: int, template_key: str) -> bool:
    """额度 -1；无余额返回 False（调用方跳过发送）。"""
    cursor = conn.execute(
        """
        UPDATE mp_subscribe_grants
        SET remaining = remaining - 1, updated_at = ?
        WHERE user_role = ? AND user_pk = ? AND template_key = ? AND remaining > 0
        """,
        (_now_iso(), user_role, int(user_pk), template_key),
    )
    return bool(cursor.rowcount)


def _clear_grants(conn: Any, user_role: str, user_pk: int, template_key: str) -> None:
    conn.execute(
        """
        UPDATE mp_subscribe_grants SET remaining = 0, updated_at = ?
        WHERE user_role = ? AND user_pk = ? AND template_key = ?
        """,
        (_now_iso(), user_role, int(user_pk), template_key),
    )


def _claim_dedupe(conn: Any, *, template_key: str, user_role: str, user_pk: int, dedupe_key: str) -> bool:
    """原子占位：同 dedupe_key 只允许一次发送（插入失败 = 已发过）。"""
    statement = insert_ignore_sql(
        get_configured_db_engine(),
        "mp_subscribe_sends",
        ("template_key", "user_role", "user_pk", "dedupe_key", "sent_at"),
        conflict_columns=("dedupe_key",),
    )
    try:
        cursor = conn.execute(
            statement.sql,
            (template_key, user_role, int(user_pk), dedupe_key, _now_iso()),
        )
    except Exception:
        return False
    return bool(cursor.rowcount)


