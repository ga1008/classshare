"""Runtime table for AI chat action proposals (engine-aware, idempotent).

A proposal is what the classroom AI prepares when a teacher asks it to *do*
something (发起投票 / 随机分组 / 结束投票). Nothing is executed until the
teacher clicks 确认 in the chat; the row records who proposed what, when it
expires, and what happened. Kept out of ``classroom_app/db`` (standard §7):
runtime-owned, short-lived, rebuildable.
"""
from __future__ import annotations

from typing import Any

from ..db.connection import get_configured_db_engine

_READY_ENGINES: set[str] = set()


def _identity_column(engine: str) -> str:
    if engine == "postgres":
        return "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    return "id INTEGER PRIMARY KEY AUTOINCREMENT"


def _table_exists(conn: Any, engine: str) -> bool:
    if engine == "postgres":
        row = conn.execute(
            "SELECT COUNT(*) AS n FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = 'ai_chat_action_proposals'"
        ).fetchone()
    else:
        row = conn.execute("SELECT COUNT(*) AS n FROM sqlite_master WHERE type = 'table' AND name = 'ai_chat_action_proposals'").fetchone()
    if row is None:
        return False
    try:
        count = row["n"]
    except (TypeError, KeyError, IndexError):
        count = row[0]
    try:
        return int(count) >= 1
    except (TypeError, ValueError):
        return False


def ensure_chat_action_schema(conn: Any) -> None:
    engine = get_configured_db_engine()
    if engine in _READY_ENGINES and _table_exists(conn, engine):
        return
    conn.execute(
        f"""
        CREATE TABLE IF NOT EXISTS ai_chat_action_proposals (
            {_identity_column(engine)},
            token TEXT NOT NULL UNIQUE,
            teacher_id INTEGER NOT NULL,
            class_offering_id INTEGER NOT NULL,
            action TEXT NOT NULL,
            params_json TEXT NOT NULL DEFAULT '{{}}',
            preview_json TEXT NOT NULL DEFAULT '{{}}',
            status TEXT NOT NULL DEFAULT 'pending',
            source_message TEXT NOT NULL DEFAULT '',
            created_at TEXT NOT NULL DEFAULT '',
            expires_at TEXT NOT NULL DEFAULT '',
            executed_at TEXT NOT NULL DEFAULT '',
            result_json TEXT NOT NULL DEFAULT '{{}}',
            error_text TEXT NOT NULL DEFAULT ''
        )
        """
    )
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_ai_chat_action_proposals_teacher ON ai_chat_action_proposals (teacher_id, status, created_at)"
    )
    _READY_ENGINES.add(engine)
