"""学生成就徽章系统。

离散成就（徽章）与连续数值的修为体系互补：条件全部从既有数据表推导，
评定幂等（UNIQUE 约束 + 先查后插），解锁时发一条消息中心通知（按徽章去重）。

扩展方式：往 ``BADGES`` 注册表追加定义 + 在 ``_compute_facts`` 里补一个事实数字，
其余（评定/通知/成就墙/进度提示）自动生效。未来事件总线可在任何领域事件后
调用 ``evaluate_and_award`` 而无需改这里的结构。
"""

