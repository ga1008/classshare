"""保持登录（remember me）：长期设备凭据 + 会话过期后静默续登。

Design (docs/remember-login-2026-10-26.md):

* Opt-in per login ("30 天内保持登录"), default off because classroom PCs are
  shared. The browser keeps one httpOnly cookie ``ls_remember`` holding
  ``<selector>.<validator>``; the server stores only ``sha256(validator)``.
* When the 24 h access session is gone, ``remember_login_middleware`` silently
  issues a new access token and rotates the validator. Expiry is sliding
  (``REMEMBER_LOGIN_DAYS``, default 30) with an absolute cap since the original
  password login (``REMEMBER_LOGIN_MAX_DAYS``, default 180).
* The platform keeps ONE live session per account. A remembered device only
  re-logs in when the account has no live session, or when the live session is
  the one this device created itself; otherwise another device is in use and the
  login page explains it instead of kicking that device out (no ping-pong).
* Presenting an old validator outside the short rotation grace window means the
  cookie was copied: every remembered device of that account is revoked and the
  session ends (``remember_notice = "security"`` on the login page).
* Any credential/authority change (password change or reset, account disabled,
  student status change, forced offline) revokes all remembered devices; a
  deliberate logout revokes only the current device.

The table is runtime-owned (kept out of ``classroom_app/db``) like
``cultivation_display_settings``.
"""
from __future__ import annotations

import hashlib
import hmac
import os
import secrets
import threading
import time
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from typing import Any, Optional

from ..database import get_db_connection
from ..db.connection import get_configured_db_engine
from ..db.savepoint import best_effort

REMEMBER_COOKIE = "ls_remember"
NOTICE_COOKIE = "ls_remember_notice"
NOTICE_COOKIE_SECONDS = 600
DEFAULT_IDLE_DAYS = 30
DEFAULT_MAX_DAYS = 180
DEFAULT_MAX_DEVICES = 5
ROTATION_GRACE_SECONDS = 120
SELECTOR_BYTES = 12
VALIDATOR_BYTES = 32
VALID_ROLES = frozenset({"student", "teacher"})
NOTICE_CONFLICT = "conflict"
NOTICE_SECURITY = "security"
NOTICE_MESSAGES = {
    NOTICE_CONFLICT: "该账号正在另一台设备上使用，本设备没有自动登录。重新登录后，另一台设备会退出。",
    NOTICE_SECURITY: "检测到保持登录凭据被重复使用，已为安全起见退出该账号所有已记住的设备。请重新登录，并建议修改密码。",
}

_READY_ENGINES: set[str] = set()
_REFRESH_LOCK = threading.Lock()
# selector -> (old_validator_hash, cookie_value, access_token, monotonic_at).
# The app runs a single worker, so this is the only refresh authority: parallel
# requests that still carry the pre-rotation cookie receive the same result
# instead of tripping theft detection or creating competing sessions.
_RECENT_REFRESHES: dict[str, tuple[str, str, str, float]] = {}


# ---------------------------------------------------------------- settings

def _env_int(name: str, default: int, low: int, high: int) -> int:
    try:
        value = int(str(os.environ.get(name, default)).strip())
    except (TypeError, ValueError):
        return default
    return max(low, min(high, value))


def remember_enabled() -> bool:
    raw = str(os.environ.get("REMEMBER_LOGIN_ENABLED", "true")).strip().lower()
    return raw not in {"0", "false", "no", "off"}


def remember_idle_days() -> int:
    return _env_int("REMEMBER_LOGIN_DAYS", DEFAULT_IDLE_DAYS, 1, 90)


def remember_max_days() -> int:
    return _env_int("REMEMBER_LOGIN_MAX_DAYS", DEFAULT_MAX_DAYS, remember_idle_days(), 365)


def remember_max_devices() -> int:
    return _env_int("REMEMBER_LOGIN_MAX_DEVICES", DEFAULT_MAX_DEVICES, 1, 20)


def login_page_remember_context() -> dict[str, Any]:
    return {"remember_login_enabled": remember_enabled(), "remember_login_days": remember_idle_days()}


# ---------------------------------------------------------------- schema

def _row_value(row: Any, key: str, index: int = 0) -> Any:
    try:
        return row[key]
    except (TypeError, KeyError, IndexError):
        return row[index]


def _table_exists(conn: Any, engine: str) -> bool:
    if engine == "postgres":
        sql = ("SELECT COUNT(*) AS n FROM information_schema.tables "
               "WHERE table_schema = current_schema() AND table_name = 'remember_login_tokens'")
    else:
        sql = "SELECT COUNT(*) AS n FROM sqlite_master WHERE type = 'table' AND name = 'remember_login_tokens'"
    row = conn.execute(sql).fetchone()
    try:
        return row is not None and int(_row_value(row, "n")) >= 1
    except (TypeError, ValueError):
        return False


def ensure_remember_schema(conn: Any) -> None:
    engine = get_configured_db_engine()
    if engine in _READY_ENGINES and _table_exists(conn, engine):
        return
    id_column = ("id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if engine == "postgres"
                 else "id INTEGER PRIMARY KEY AUTOINCREMENT")
    with best_effort(conn, "remember_login_ddl"):
        conn.execute(
            f"""
            CREATE TABLE IF NOT EXISTS remember_login_tokens (
                {id_column},
                selector TEXT NOT NULL UNIQUE,
                validator_hash TEXT NOT NULL,
                prev_validator_hash TEXT NOT NULL DEFAULT '',
                rotated_at TEXT NOT NULL DEFAULT '',
                user_id TEXT NOT NULL,
                role TEXT NOT NULL,
                last_session_id TEXT NOT NULL DEFAULT '',
                device_label TEXT NOT NULL DEFAULT '',
                ip TEXT NOT NULL DEFAULT '',
                created_at TEXT NOT NULL,
                last_used_at TEXT NOT NULL,
                expires_at TEXT NOT NULL,
                absolute_expires_at TEXT NOT NULL,
                revoked_at TEXT NOT NULL DEFAULT '',
                revoke_reason TEXT NOT NULL DEFAULT ''
            )
            """
        )
        conn.execute(
            "CREATE INDEX IF NOT EXISTS idx_remember_login_tokens_user "
            "ON remember_login_tokens (user_id, role, revoked_at)"
        )
    if _table_exists(conn, engine):
        _READY_ENGINES.add(engine)


# ---------------------------------------------------------------- primitives

def _utc_now() -> datetime:
    return datetime.now(timezone.utc)


def _iso(value: datetime) -> str:
    return value.isoformat()


def _hash_validator(validator: str) -> str:
    return hashlib.sha256(str(validator).encode("utf-8")).hexdigest()


def parse_remember_cookie(value: Any) -> Optional[tuple[str, str]]:
    raw = str(value or "").strip()
    selector, sep, validator = raw.partition(".")
    if not sep or not selector or not validator or len(raw) > 200:
        return None
    if not all(ch.isalnum() or ch in "-_" for ch in selector + validator):
        return None
    return selector, validator


def _new_secret_pair() -> tuple[str, str]:
    return secrets.token_urlsafe(SELECTOR_BYTES), secrets.token_urlsafe(VALIDATOR_BYTES)


def _device_label(user_agent: str) -> str:
    try:
        from .student_auth_service import parse_user_agent
        return str(parse_user_agent(user_agent).get("device_label") or "")[:80]
    except Exception:  # noqa: BLE001 - a label is decoration only
        return ""


def _mask_ip(ip: str) -> str:
    value = str(ip or "").strip()
    if not value:
        return ""
    if ":" in value:
        return value.split(":")[0] + ":…"
    parts = value.split(".")
    return ".".join(parts[:2] + ["*", "*"]) if len(parts) == 4 else value


def is_https_request(request: Any) -> bool:
    forwarded = str(request.headers.get("x-forwarded-proto") or "").split(",")[0].strip().lower()
    return forwarded == "https" or str(getattr(request.url, "scheme", "")).lower() == "https"


def apply_remember_cookie(response: Any, cookie_value: str, *, secure: bool) -> None:
    max_age = remember_idle_days() * 86400
    response.set_cookie(
        key=REMEMBER_COOKIE, value=cookie_value, max_age=max_age, expires=max_age,
        httponly=True, samesite="lax", secure=bool(secure), path="/",
    )


def clear_remember_cookie(response: Any) -> None:
    response.delete_cookie(REMEMBER_COOKIE, path="/")


def set_notice_cookie(response: Any, kind: str) -> None:
    """Carry a security notice across the redirect to the login page."""
    response.set_cookie(key=NOTICE_COOKIE, value=kind, max_age=NOTICE_COOKIE_SECONDS,
                        httponly=True, samesite="lax", path="/")


def notice_for_request(request: Any) -> str:
    kind = getattr(getattr(request, "state", None), "remember_notice", "") or request.cookies.get(NOTICE_COOKIE, "")
    return NOTICE_MESSAGES.get(str(kind or ""), "")


# ---------------------------------------------------------------- issue / revoke

def _active_rows(conn: Any, user_id: str, role: str) -> list[Any]:
    return conn.execute(
        """
        SELECT id, selector, created_at, last_used_at
        FROM remember_login_tokens
        WHERE user_id = ? AND role = ? AND revoked_at = ''
        ORDER BY last_used_at DESC, id DESC
        """,
        (str(user_id), str(role)),
    ).fetchall()


def _revoke_ids(conn: Any, ids: list[int], reason: str) -> int:
    if not ids:
        return 0
    placeholders = ", ".join("?" for _ in ids)
    cursor = conn.execute(
        f"UPDATE remember_login_tokens SET revoked_at = ?, revoke_reason = ? "
        f"WHERE id IN ({placeholders}) AND revoked_at = ''",
        (_iso(_utc_now()), str(reason)[:60], *ids),
    )
    return int(getattr(cursor, "rowcount", 0) or 0)


def issue_remember_token(
    conn: Any, *, user_id: Any, role: str, session_id: str, user_agent: str = "", ip: str = "",
    absolute_expires_at: Optional[str] = None,
) -> str:
    """Create a remembered device and return the cookie value. Caller commits."""
    ensure_remember_schema(conn)
    normalized_role = str(role or "").strip().lower()
    if normalized_role not in VALID_ROLES:
        raise ValueError("remember login supports students and teachers only")
    now = _utc_now()
    selector, validator = _new_secret_pair()
    conn.execute(
        """
        INSERT INTO remember_login_tokens (
            selector, validator_hash, user_id, role, last_session_id, device_label, ip,
            created_at, last_used_at, expires_at, absolute_expires_at
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """,
        (
            selector, _hash_validator(validator), str(user_id), normalized_role, str(session_id or ""),
            _device_label(user_agent), str(ip or "")[:64], _iso(now), _iso(now),
            _iso(now + timedelta(days=remember_idle_days())),
            absolute_expires_at or _iso(now + timedelta(days=remember_max_days())),
        ),
    )
    rows = _active_rows(conn, str(user_id), normalized_role)
    overflow = [int(_row_value(row, "id")) for row in rows[remember_max_devices():]]
    _revoke_ids(conn, overflow, "device_limit")
    return f"{selector}.{validator}"


def revoke_remember_tokens(conn: Any, user_id: Any, role: Optional[str], reason: str) -> int:
    """Revoke every remembered device of an account (role None = both roles)."""
    ensure_remember_schema(conn)
    params: list[Any] = [_iso(_utc_now()), str(reason)[:60], str(user_id)]
    role_sql = ""
    if role:
        role_sql = " AND role = ?"
        params.append(str(role).strip().lower())
    cursor = conn.execute(
        "UPDATE remember_login_tokens SET revoked_at = ?, revoke_reason = ? "
        f"WHERE user_id = ? AND revoked_at = ''{role_sql}",
        tuple(params),
    )
    return int(getattr(cursor, "rowcount", 0) or 0)


def revoke_remember_selector(conn: Any, selector: str, reason: str) -> int:
    ensure_remember_schema(conn)
    cursor = conn.execute(
        "UPDATE remember_login_tokens SET revoked_at = ?, revoke_reason = ? WHERE selector = ? AND revoked_at = ''",
        (_iso(_utc_now()), str(reason)[:60], str(selector)),
    )
    _RECENT_REFRESHES.pop(str(selector), None)
    return int(getattr(cursor, "rowcount", 0) or 0)


def revoke_remember_tokens_standalone(user_id: Any, role: Optional[str], reason: str) -> int:
    with get_db_connection() as conn:
        count = revoke_remember_tokens(conn, user_id, role, reason)
        conn.commit()
    return count


# ---------------------------------------------------------------- login wiring

def _payload_from_access_token(access_token: str) -> dict[str, Any]:
    from ..dependencies import decode_token_payload
    return decode_token_payload(access_token) or {}


def update_remember_after_login(request: Any, response: Any, access_token: str, remember: bool) -> None:
    """Run after any interactive password login on this device.

    Ticked: replace this device's previous token with a fresh one. Not ticked:
    revoke and clear whatever this device remembered (possibly another user).
    """
    if NOTICE_COOKIE in request.cookies:
        response.delete_cookie(NOTICE_COOKIE, path="/")
    if not remember_enabled():
        return
    previous = parse_remember_cookie(request.cookies.get(REMEMBER_COOKIE))
    if not remember and not previous:
        return  # the common case: nothing remembered, nothing to remember
    payload = _payload_from_access_token(access_token)
    with get_db_connection() as conn:
        ensure_remember_schema(conn)
        if previous:
            revoke_remember_selector(conn, previous[0], "replaced_by_login")
        cookie_value = ""
        if remember and payload.get("id") is not None:
            cookie_value = issue_remember_token(
                conn, user_id=payload.get("id"), role=str(payload.get("role") or ""),
                session_id=str(payload.get("session_id") or ""),
                user_agent=str(request.headers.get("user-agent") or ""), ip=str(payload.get("ip") or ""),
            )
        conn.commit()
    if cookie_value:
        apply_remember_cookie(response, cookie_value, secure=is_https_request(request))
    elif previous:
        clear_remember_cookie(response)


def current_device_remembered(request: Any, user: dict[str, Any]) -> Optional[str]:
    """This device's absolute expiry if it is validly remembered for ``user``.

    Read it before a credential change (which revokes every device) so the
    device the user is actually using can stay remembered afterwards.
    """
    parsed = parse_remember_cookie(request.cookies.get(REMEMBER_COOKIE))
    if not parsed or not remember_enabled():
        return None
    selector, validator = parsed
    with get_db_connection() as conn:
        ensure_remember_schema(conn)
        row = conn.execute(
            "SELECT user_id, role, validator_hash, revoked_at, absolute_expires_at FROM remember_login_tokens "
            "WHERE selector = ? LIMIT 1",
            (selector,),
        ).fetchone()
    if row is None or str(row["revoked_at"] or ""):
        return None
    if str(row["user_id"]) != str(user.get("id")) or str(row["role"]) != str(user.get("role") or ""):
        return None
    if not hmac.compare_digest(str(row["validator_hash"]), _hash_validator(validator)):
        return None
    return str(row["absolute_expires_at"] or "") or None


def reissue_for_current_device(request: Any, response: Any, user: dict[str, Any], absolute_expires_at: str) -> None:
    """After a self password change: keep the device the user is using remembered."""
    from ..dependencies import decode_token_payload
    payload = decode_token_payload(request.cookies.get("access_token")) or {}
    with get_db_connection() as conn:
        cookie_value = issue_remember_token(
            conn, user_id=user.get("id"), role=str(user.get("role") or ""),
            session_id=str(payload.get("session_id") or ""),
            user_agent=str(request.headers.get("user-agent") or ""), ip=str(payload.get("ip") or ""),
            absolute_expires_at=absolute_expires_at,
        )
        conn.commit()
    apply_remember_cookie(response, cookie_value, secure=is_https_request(request))


# ---------------------------------------------------------------- refresh

@dataclass(frozen=True)
class RememberOutcome:
    kind: str  # ok | clear | conflict | security | skip
    access_token: str = ""
    cookie_value: str = ""


def _account_token_data(conn: Any, user_id: str, role: str) -> Optional[dict[str, Any]]:
    """Login claims for an account that may still sign in, else None."""
    if not str(user_id).isdigit():
        return None
    login_time = datetime.now().isoformat()
    if role == "teacher":
        row = conn.execute(
            "SELECT id, name, email, COALESCE(is_active, 1) AS is_active FROM teachers WHERE id = ? LIMIT 1",
            (int(user_id),),
        ).fetchone()
        if row is None or int(row["is_active"] or 0) != 1:
            return None
        return {"id": row["id"], "name": row["name"], "email": row["email"], "role": "teacher",
                "login_time": login_time, "auth_method": "remember"}
    row = conn.execute(
        "SELECT id, name, student_id_number, COALESCE(enrollment_status, 'active') AS enrollment_status, "
        "COALESCE(password_reset_required, 0) AS password_reset_required FROM students WHERE id = ? LIMIT 1",
        (int(user_id),),
    ).fetchone()
    if row is None or str(row["enrollment_status"] or "active").strip().lower() != "active":
        return None
    if int(row["password_reset_required"] or 0):
        return None
    return {"id": row["id"], "student_id_number": row["student_id_number"], "name": row["name"],
            "role": "student", "login_time": login_time, "auth_method": "remember"}


def _another_device_is_live(user_id: str, role: str, last_session_id: str) -> bool:
    from ..db.sessions import get_user_session
    from ..dependencies import build_session_user_key
    current = get_user_session(build_session_user_key(user_id, role) or "")
    return bool(current) and str(current.get("session_id") or "") != str(last_session_id or "")


def _theft_detected(conn: Any, row: Any) -> RememberOutcome:
    user_id, role = str(row["user_id"]), str(row["role"])
    revoke_remember_tokens(conn, user_id, role, "reuse_detected")
    conn.commit()
    from ..dependencies import invalidate_session_for_user
    invalidate_session_for_user(user_id, role, revoke_remembered=False)
    print(f"[REMEMBER] reused remember token for {role}:{user_id}; all remembered devices revoked")
    return RememberOutcome(NOTICE_SECURITY)


def _validator_mismatch(conn: Any, row: Any, presented_hash: str, now: datetime) -> RememberOutcome:
    try:
        rotated_at = datetime.fromisoformat(str(row["rotated_at"]))
        rotated_recently = (now - rotated_at).total_seconds() <= ROTATION_GRACE_SECONDS
    except ValueError:
        rotated_recently = False
    if rotated_recently and hmac.compare_digest(str(row["prev_validator_hash"] or ""), presented_hash):
        return RememberOutcome("skip")  # a parallel request already rotated; let this one pass
    return _theft_detected(conn, row)


def _rotate(conn: Any, row: Any, selector: str, client_ip: str, user_agent: str,
            token_data: dict[str, Any], now: datetime) -> tuple[str, str]:
    from ..dependencies import create_access_token, decode_token_payload
    access_token = create_access_token(token_data, client_ip)
    session_id = str((decode_token_payload(access_token) or {}).get("session_id") or "")
    new_validator = secrets.token_urlsafe(VALIDATOR_BYTES)
    new_expiry = min(now + timedelta(days=remember_idle_days()),
                     datetime.fromisoformat(str(row["absolute_expires_at"])))
    now_iso = _iso(now)
    conn.execute(
        """
        UPDATE remember_login_tokens
        SET prev_validator_hash = validator_hash, validator_hash = ?, rotated_at = ?, last_used_at = ?,
            expires_at = ?, last_session_id = ?, ip = ?, device_label = ?
        WHERE selector = ? AND revoked_at = ''
        """,
        (_hash_validator(new_validator), now_iso, now_iso, _iso(new_expiry), session_id,
         str(client_ip or "")[:64], _device_label(user_agent) or str(row["device_label"] or ""), selector),
    )
    conn.commit()
    return access_token, f"{selector}.{new_validator}"


def _refresh_locked(selector: str, validator: str, client_ip: str, user_agent: str) -> RememberOutcome:
    presented_hash = _hash_validator(validator)
    cached = _RECENT_REFRESHES.get(selector)
    if cached and time.monotonic() - cached[3] <= ROTATION_GRACE_SECONDS:
        if hmac.compare_digest(cached[0], presented_hash):
            return RememberOutcome("ok", access_token=cached[2], cookie_value=cached[1])
    now = _utc_now()
    now_iso = _iso(now)
    with get_db_connection() as conn:
        ensure_remember_schema(conn)
        row = conn.execute("SELECT * FROM remember_login_tokens WHERE selector = ? LIMIT 1", (selector,)).fetchone()
        if row is None or str(row["revoked_at"] or ""):
            return RememberOutcome("clear")
        if str(row["expires_at"]) <= now_iso or str(row["absolute_expires_at"]) <= now_iso:
            revoke_remember_selector(conn, selector, "expired")
            conn.commit()
            return RememberOutcome("clear")
        if not hmac.compare_digest(str(row["validator_hash"]), presented_hash):
            return _validator_mismatch(conn, row, presented_hash, now)
        user_id, role = str(row["user_id"]), str(row["role"])
        token_data = _account_token_data(conn, user_id, role)
        if token_data is None:
            revoke_remember_tokens(conn, user_id, role, "account_unavailable")
            conn.commit()
            return RememberOutcome("clear")
        if _another_device_is_live(user_id, role, str(row["last_session_id"] or "")):
            return RememberOutcome(NOTICE_CONFLICT)
        access_token, cookie_value = _rotate(conn, row, selector, client_ip, user_agent, token_data, now)
    _RECENT_REFRESHES[selector] = (presented_hash, cookie_value, access_token, time.monotonic())
    if len(_RECENT_REFRESHES) > 2000:
        _RECENT_REFRESHES.clear()
    print(f"[REMEMBER] silent re-login for {role}:{user_id}")
    return RememberOutcome("ok", access_token=access_token, cookie_value=cookie_value)


def refresh_from_remember_cookie(cookie_value: Any, client_ip: str, user_agent: str) -> RememberOutcome:
    parsed = parse_remember_cookie(cookie_value)
    if not parsed:
        return RememberOutcome("clear")
    with _REFRESH_LOCK:
        try:
            return _refresh_locked(parsed[0], parsed[1], client_ip, user_agent)
        except Exception as exc:  # noqa: BLE001 - never break the request because of remember-me
            print(f"[REMEMBER] refresh failed: {exc}")
            return RememberOutcome("skip")


# ---------------------------------------------------------------- device management

def list_remembered_devices(conn: Any, user: dict[str, Any], current: str = "") -> list[dict[str, Any]]:
    ensure_remember_schema(conn)
    now_iso = _iso(_utc_now())
    rows = conn.execute(
        """
        SELECT id, selector, device_label, ip, created_at, last_used_at, expires_at, absolute_expires_at
        FROM remember_login_tokens
        WHERE user_id = ? AND role = ? AND revoked_at = '' AND expires_at > ? AND absolute_expires_at > ?
        ORDER BY last_used_at DESC, id DESC
        """,
        (str(user.get("id")), str(user.get("role") or ""), now_iso, now_iso),
    ).fetchall()
    return [
        {
            "id": int(row["id"]),
            "device_label": str(row["device_label"] or "") or "未识别设备",
            "ip": _mask_ip(str(row["ip"] or "")),
            "created_at": str(row["created_at"] or ""),
            "last_used_at": str(row["last_used_at"] or ""),
            "expires_at": min(str(row["expires_at"] or ""), str(row["absolute_expires_at"] or "")),
            "current": bool(current) and str(row["selector"]) == current,
        }
        for row in rows
    ]


def revoke_device(conn: Any, user: dict[str, Any], token_id: int) -> bool:
    ensure_remember_schema(conn)
    row = conn.execute(
        "SELECT selector FROM remember_login_tokens WHERE id = ? AND user_id = ? AND role = ? AND revoked_at = ''",
        (int(token_id), str(user.get("id")), str(user.get("role") or "")),
    ).fetchone()
    if row is None:
        return False
    return revoke_remember_selector(conn, str(row["selector"]), "user_revoked") > 0


def current_selector(request: Any) -> str:
    parsed = parse_remember_cookie(request.cookies.get(REMEMBER_COOKIE))
    return parsed[0] if parsed else ""
