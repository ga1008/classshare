"""Immutable teacher-owned project package versions and their exact resource scopes."""

from .connection import get_configured_db_engine


def ensure_project_topic_packages_schema(conn) -> None:
    id_type = ("BIGINT GENERATED BY DEFAULT AS IDENTITY" if get_configured_db_engine() == "postgres"
               else "INTEGER")
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS project_topic_packages (
            id {id_type} PRIMARY KEY,
            teacher_id INTEGER NOT NULL, package_key TEXT NOT NULL, title TEXT NOT NULL,
            version TEXT NOT NULL, fingerprint TEXT NOT NULL, mapping_confirmed INTEGER NOT NULL,
            manifest_json TEXT NOT NULL, common_json TEXT NOT NULL,
            issues_json TEXT NOT NULL, common_issues_json TEXT NOT NULL,
            created_at TEXT NOT NULL, UNIQUE (teacher_id, fingerprint)
        )
    """)
    conn.execute("""CREATE INDEX IF NOT EXISTS idx_project_topic_packages_owner
                    ON project_topic_packages(teacher_id,id DESC)""")
    conn.execute("""
        CREATE TABLE IF NOT EXISTS project_topic_items (
            package_id BIGINT NOT NULL REFERENCES project_topic_packages(id) ON DELETE CASCADE,
            topic_key TEXT NOT NULL, ordinal INTEGER NOT NULL, item_json TEXT NOT NULL,
            PRIMARY KEY (package_id, topic_key)
        )""")
    conn.execute("""
        CREATE TABLE IF NOT EXISTS project_topic_files (
            package_id BIGINT NOT NULL REFERENCES project_topic_packages(id) ON DELETE CASCADE,
            path TEXT NOT NULL, file_hash TEXT NOT NULL, size_bytes BIGINT NOT NULL,
            PRIMARY KEY (package_id,path)
        )""")
    conn.execute("""CREATE INDEX IF NOT EXISTS idx_project_topic_files_hash ON project_topic_files(file_hash)""")
    conn.execute("""
        CREATE TABLE IF NOT EXISTS project_topic_resource_scopes (
            package_id BIGINT NOT NULL, topic_key TEXT NOT NULL, path TEXT NOT NULL,
            PRIMARY KEY (package_id, topic_key, path),
            FOREIGN KEY (package_id,path) REFERENCES project_topic_files(package_id,path) ON DELETE CASCADE
        )""")
