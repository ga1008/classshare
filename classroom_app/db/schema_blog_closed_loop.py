"""Blog closed-loop data model (docs/blog-closed-loop-plan-2026-10-12.md §8).

New tables for content review, appeals, safety terms, comment media, author
statistics and notification preferences. The DDL is engine-aware and
idempotent, so it is ensured at runtime on both SQLite and PostgreSQL without
touching the central SQLite->PostgreSQL migration — mirroring ``schema_polls``.

Columns added to existing tables (``blog_posts``, ``blog_comments``,
``blog_follows``, ``blog_moderation_logs``, ``message_center_notifications``)
live with those tables: ``schema_learning_blog`` / ``schema_classroom_activity``
for SQLite and ``POSTGRES_RUNTIME_COLUMN_DEFINITIONS`` for PostgreSQL.

``backfill_blog_closed_loop_data`` derives the new columns from legacy data.
Each step is guarded by its own condition, so it is safe and cheap to run on
every startup, and a dry run reports exactly what an apply would change.
Legacy ``blog_posts.status`` values are deliberately left untouched until the
read paths switch to ``moderation_state`` (P3); rewriting them earlier would
make moderator-hidden posts visible in between.
"""

from __future__ import annotations

import json
import re
from typing import Any

from .connection import get_configured_db_engine

LEGACY_MODERATION_NOTE = "此帖在系统升级前被处理，原因未记录。如有疑问可申诉。"
# Comment rows scanned for media per run; the remainder is picked up next run.
COMMENT_MEDIA_BACKFILL_BATCH = 500
# A reply chain deeper than this is not plausible; it only bounds the loop.
ROOT_BACKFILL_MAX_DEPTH = 64
_BLOG_IMAGE_HASH_RE = re.compile(r"/api/blog/image/([a-f0-9]{64})")
_FILE_HASH_RE = re.compile(r"^[a-f0-9]{64}$")


def ensure_blog_closed_loop_schema(conn: Any, *, engine: str | None = None) -> None:
    """Create the blog closed-loop tables on either engine (idempotent).

    ``engine`` must be passed when the connection's dialect can differ from the
    configured one: the PostgreSQL index harvester builds an in-memory SQLite
    copy of the blog schema even when ``DB_ENGINE=postgres``. No module-level
    "ready" cache: it is only called at startup/schema ensure, and a cache would
    skip fresh databases created later in the same process (tests, tools).
    """
    engine = engine or get_configured_db_engine()
    id_column = (
        "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        if engine == "postgres"
        else "id INTEGER PRIMARY KEY AUTOINCREMENT"
    )

    # One verdict per (target, content revision, layer). A late result for an
    # older revision is recognisable and ignored (AI durable-job invariant).
    conn.execute(
        f"""
        CREATE TABLE IF NOT EXISTS blog_content_reviews (
            {id_column},
            target_type TEXT NOT NULL,
            target_id INTEGER NOT NULL,
            content_revision INTEGER NOT NULL DEFAULT 1,
            layer TEXT NOT NULL DEFAULT 'ai',
            status TEXT NOT NULL DEFAULT 'pending',
            risk TEXT NOT NULL DEFAULT '',
            categories_json TEXT NOT NULL DEFAULT '[]',
            evidence TEXT NOT NULL DEFAULT '',
            author_note TEXT NOT NULL DEFAULT '',
            model TEXT NOT NULL DEFAULT '',
            error_message TEXT NOT NULL DEFAULT '',
            created_at TEXT NOT NULL,
            finished_at TEXT,
            UNIQUE (target_type, target_id, content_revision, layer)
        )
        """
    )
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_blog_content_reviews_status "
        "ON blog_content_reviews (status, created_at)"
    )

    # Which stored images a comment references, so image authorisation becomes
    # an indexed join instead of a LIKE scan over every comment body.
    conn.execute(
        f"""
        CREATE TABLE IF NOT EXISTS blog_comment_media (
            {id_column},
            comment_id INTEGER NOT NULL,
            post_id INTEGER NOT NULL,
            file_hash TEXT NOT NULL,
            media_kind TEXT NOT NULL DEFAULT 'attachment',
            created_at TEXT NOT NULL,
            UNIQUE (comment_id, file_hash, media_kind)
        )
        """
    )
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_blog_comment_media_hash "
        "ON blog_comment_media (file_hash, comment_id)"
    )

    conn.execute(
        f"""
        CREATE TABLE IF NOT EXISTS blog_appeals (
            {id_column},
            target_type TEXT NOT NULL,
            target_id INTEGER NOT NULL,
            moderation_log_id INTEGER,
            author_identity TEXT NOT NULL,
            reason TEXT NOT NULL DEFAULT '',
            status TEXT NOT NULL DEFAULT 'pending',
            decided_by TEXT NOT NULL DEFAULT '',
            decision TEXT NOT NULL DEFAULT '',
            decision_note TEXT NOT NULL DEFAULT '',
            created_at TEXT NOT NULL,
            decided_at TEXT,
            UNIQUE (target_type, target_id, moderation_log_id)
        )
        """
    )
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_blog_appeals_status "
        "ON blog_appeals (status, created_at)"
    )
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_blog_appeals_author "
        "ON blog_appeals (author_identity, created_at)"
    )

    # Local (L1) safety terms. level: 'block' refuses the write; 'flag' stores
    # it but holds it for review.
    conn.execute(
        f"""
        CREATE TABLE IF NOT EXISTS blog_safety_terms (
            {id_column},
            term TEXT NOT NULL,
            level TEXT NOT NULL DEFAULT 'flag',
            category TEXT NOT NULL DEFAULT 'other',
            enabled INTEGER NOT NULL DEFAULT 1,
            updated_by TEXT NOT NULL DEFAULT '',
            updated_at TEXT NOT NULL,
            UNIQUE (term)
        )
        """
    )

    # Per author *face* (identity + display mode) per day, so pen-name numbers
    # never reveal real-name totals. Derived data; safe to recompute.
    conn.execute(
        f"""
        CREATE TABLE IF NOT EXISTS blog_author_daily_stats (
            {id_column},
            author_identity TEXT NOT NULL,
            display_mode TEXT NOT NULL DEFAULT 'real_name',
            stat_date TEXT NOT NULL,
            views INTEGER NOT NULL DEFAULT 0,
            readers INTEGER NOT NULL DEFAULT 0,
            completed_reads INTEGER NOT NULL DEFAULT 0,
            likes INTEGER NOT NULL DEFAULT 0,
            comments INTEGER NOT NULL DEFAULT 0,
            followers_delta INTEGER NOT NULL DEFAULT 0,
            updated_at TEXT NOT NULL,
            UNIQUE (author_identity, display_mode, stat_date)
        )
        """
    )

    # Generic per-user mute switches for message-center events (not blog-only).
    conn.execute(
        f"""
        CREATE TABLE IF NOT EXISTS user_notification_preferences (
            {id_column},
            identity TEXT NOT NULL,
            event_key TEXT NOT NULL,
            enabled INTEGER NOT NULL DEFAULT 1,
            updated_at TEXT NOT NULL,
            UNIQUE (identity, event_key)
        )
        """
    )

    # P3: teachers granted blog moderation (plan D7); super admins always are.
    # Revoking keeps the row (revoked_at/revoked_by) as the grant's audit trail.
    conn.execute(
        f"""
        CREATE TABLE IF NOT EXISTS blog_moderators (
            {id_column},
            teacher_id INTEGER NOT NULL UNIQUE,
            granted_by TEXT NOT NULL DEFAULT '',
            created_at TEXT NOT NULL,
            revoked_by TEXT NOT NULL DEFAULT '',
            revoked_at TEXT
        )
        """
    )

    # P2: an anonymous commenter's code within one post ("匿名同学·青柚").
    # The two UNIQUE constraints make the code stable per person and distinct
    # per post even when two first comments race; deleting comments never
    # releases a code (it would let a later voice inherit someone's history).
    conn.execute(
        f"""
        CREATE TABLE IF NOT EXISTS blog_anonymous_codes (
            {id_column},
            post_id INTEGER NOT NULL,
            author_identity TEXT NOT NULL,
            code TEXT NOT NULL,
            created_at TEXT NOT NULL,
            UNIQUE (post_id, author_identity),
            UNIQUE (post_id, code)
        )
        """
    )


def comment_media_rows(comment: dict[str, Any]) -> set[tuple[str, str]]:
    """(file_hash, media_kind) pairs a comment references: attachments,
    custom emoji and inline Markdown images. Shared by writes and backfill."""
    found: set[tuple[str, str]] = set()
    for kind, raw in (("attachment", comment.get("attachments_json")), ("emoji", comment.get("emoji_payload_json"))):
        try:
            items = json.loads(raw) if raw else []
        except (TypeError, ValueError):
            items = []
        for item in items if isinstance(items, list) else []:
            file_hash = str(item.get("file_hash") or "").strip().lower() if isinstance(item, dict) else ""
            if _FILE_HASH_RE.match(file_hash):
                found.add((file_hash, kind))
    for file_hash in _BLOG_IMAGE_HASH_RE.findall(str(comment.get("content_md") or "").lower()):
        found.add((file_hash, "inline"))
    return found


def insert_comment_media(conn: Any, comment_id: int, post_id: int, file_hash: str, media_kind: str, now: str) -> None:
    conn.execute(
        """
        INSERT INTO blog_comment_media (comment_id, post_id, file_hash, media_kind, created_at)
        SELECT ?, ?, ?, ?, ?
        WHERE NOT EXISTS (
            SELECT 1 FROM blog_comment_media WHERE comment_id = ? AND file_hash = ? AND media_kind = ?
        )
        """,
        (comment_id, post_id, file_hash, media_kind, now, comment_id, file_hash, media_kind),
    )


def _table_exists(conn: Any, table: str) -> bool:
    if get_configured_db_engine() == "postgres":
        row = conn.execute(
            "SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = ?",
            (table,),
        ).fetchone()
    else:
        row = conn.execute("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?", (table,)).fetchone()
    return row is not None


def _count(conn: Any, sql: str, params: tuple = ()) -> int:
    row = conn.execute(sql, params).fetchone()
    return int(row[0] or 0) if row else 0


def _guarded_update(conn: Any, report: dict[str, int], key: str, where: str, set_sql: str,
                    params: tuple, apply: bool, table: str) -> None:
    pending = _count(conn, f"SELECT COUNT(*) FROM {table} WHERE {where}")
    report[key] = pending
    if apply and pending:
        conn.execute(f"UPDATE {table} SET {set_sql} WHERE {where}", params)


def backfill_blog_closed_loop_data(conn: Any, *, apply: bool = True, now: str = "") -> dict[str, int]:
    """Derive the closed-loop columns from legacy data (idempotent).

    With ``apply=False`` nothing is written; the counts are what an apply would
    change. A database without the blog tables yields an empty report.
    """
    report: dict[str, int] = {}
    if not (_table_exists(conn, "blog_posts") and _table_exists(conn, "blog_comments")):
        return report

    # Moderator-hidden posts keep their legacy status; the new state mirrors it.
    _guarded_update(
        conn, report, "posts_marked_limited",
        "status IN ('moderated', 'hidden') "
        "AND COALESCE(moderation_state, 'none') NOT IN ('limited', 'removed', 'appeal_pending')",
        "moderation_state = 'limited', "
        "moderation_reason_code = CASE WHEN COALESCE(moderation_reason_code, '') = '' THEN 'other' ELSE moderation_reason_code END, "
        "moderation_note = CASE WHEN COALESCE(moderation_note, '') = '' THEN ? ELSE moderation_note END",
        (LEGACY_MODERATION_NOTE,), apply, "blog_posts",
    )
    _guarded_update(
        conn, report, "posts_marked_passed",
        "status = 'published' AND COALESCE(moderation_state, 'none') = 'none'",
        "moderation_state = 'passed'", (), apply, "blog_posts",
    )
    _guarded_update(
        conn, report, "posts_published_at",
        "published_at IS NULL AND status <> 'draft'",
        "published_at = created_at", (), apply, "blog_posts",
    )

    # P3: reads use moderation_state, so the legacy hide statuses converge to
    # "published" (their limited state was mirrored above, in the same pass).
    _guarded_update(
        conn, report, "posts_status_converged",
        "status IN ('moderated', 'hidden') "
        "AND COALESCE(moderation_state, 'none') IN ('limited', 'removed', 'appeal_pending')",
        "status = 'published', published_at = COALESCE(published_at, created_at)",
        (), apply, "blog_posts",
    )
    _guarded_update(
        conn, report, "comments_status_converged",
        "status = 'hidden'",
        "status = 'active', moderation_state = 'limited', "
        "moderation_reason_code = CASE WHEN COALESCE(moderation_reason_code, '') = '' THEN 'other' ELSE moderation_reason_code END",
        (), apply, "blog_comments",
    )
    # P2: a class tag identifies a pen-name/anonymous author; such posts never
    # show system tags, so the stored copy is dropped (it is derivable anyway).
    _guarded_update(
        conn, report, "posts_shielded_system_tags",
        "COALESCE(author_display_mode, 'real_name') <> 'real_name' "
        "AND COALESCE(system_tags_json, '') NOT IN ('', '[]')",
        "system_tags_json = '[]'", (), apply, "blog_posts",
    )
    # P2: before personas, the anonymous post's author commented under their
    # stored name. Every stored copy of such a comment's face becomes "楼主".
    _guarded_update(
        conn, report, "comments_anonymous_op",
        "COALESCE(author_display_snapshot, '') <> '楼主' AND EXISTS ("
        " SELECT 1 FROM blog_posts p WHERE p.id = blog_comments.post_id"
        " AND p.author_display_mode = 'anonymous' AND p.author_identity = blog_comments.author_identity)",
        "author_display_mode = 'anonymous', author_display_name = '楼主', author_display_snapshot = '楼主'",
        (), apply, "blog_comments",
    )

    _guarded_update(
        conn, report, "comments_reply_to",
        "reply_to_comment_id IS NULL AND parent_comment_id IS NOT NULL",
        "reply_to_comment_id = parent_comment_id", (), apply, "blog_comments",
    )
    _guarded_update(
        conn, report, "comments_root_top_level",
        "root_comment_id IS NULL AND parent_comment_id IS NULL",
        "root_comment_id = id", (), apply, "blog_comments",
    )
    # Nested replies inherit their parent's root, one level per pass.
    report["comments_root_nested"] = _count(
        conn, "SELECT COUNT(*) FROM blog_comments WHERE root_comment_id IS NULL AND parent_comment_id IS NOT NULL",
    )
    if apply and report["comments_root_nested"]:
        for _ in range(ROOT_BACKFILL_MAX_DEPTH):
            cursor = conn.execute(
                """
                UPDATE blog_comments
                SET root_comment_id = (
                    SELECT parent.root_comment_id FROM blog_comments parent
                    WHERE parent.id = blog_comments.parent_comment_id
                )
                WHERE root_comment_id IS NULL
                  AND parent_comment_id IS NOT NULL
                  AND EXISTS (
                      SELECT 1 FROM blog_comments parent
                      WHERE parent.id = blog_comments.parent_comment_id AND parent.root_comment_id IS NOT NULL
                  )
                """
            )
            if not int(cursor.rowcount or 0):
                break

    if _table_exists(conn, "blog_comment_media"):
        rows = conn.execute(
            """
            SELECT c.id, c.post_id, c.content_md, c.attachments_json, c.emoji_payload_json
            FROM blog_comments c
            WHERE (
                    COALESCE(c.attachments_json, '[]') NOT IN ('', '[]')
                 OR COALESCE(c.emoji_payload_json, '') NOT IN ('', '[]')
                 OR c.content_md LIKE '%/api/blog/image/%'
            )
              AND NOT EXISTS (SELECT 1 FROM blog_comment_media m WHERE m.comment_id = c.id)
            ORDER BY c.id
            LIMIT ?
            """,
            (COMMENT_MEDIA_BACKFILL_BATCH,),
        ).fetchall()
        media_count = 0
        for row in rows:
            for file_hash, kind in sorted(comment_media_rows(dict(row))):
                media_count += 1
                if apply:
                    insert_comment_media(conn, int(row["id"]), int(row["post_id"]), file_hash, kind, now)
        report["comment_media_rows"] = media_count
    return report
