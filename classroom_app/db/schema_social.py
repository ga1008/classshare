# Columns added after the first release: (table, column, definition). Existing
# databases get them through ``_add_column_if_missing`` before the indexes run.
# ``global_file_hash`` mirrors ``blob_hash`` only while the row references the
# read-only global store, so ``file_service.count_global_file_references``
# (which discovers every ``*_file_hash`` column) sees social references
# (docs/global-file-reference-protocol.md); it is cleared on expiry.
_ADDED_COLUMNS = (
    ("social_message_media", "global_file_hash", "TEXT NOT NULL DEFAULT ''"),
    ("social_media_tokens", "global_file_hash", "TEXT NOT NULL DEFAULT ''"),
)


def social_schema_statements(engine: str) -> list[str]:
    """Every CREATE statement for ``engine`` ('sqlite' | 'postgres'), in execution order."""
    normalized = str(engine or "sqlite").strip().lower()
    return [*_table_statements(_id_column(normalized)), *_INDEX_STATEMENTS]


def _add_column_if_missing(conn: Any, engine: str, table: str, column: str, definition: str) -> None:
    if engine == "postgres":
        conn.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column} {definition}")
        return
    existing = {str(row[1]) for row in conn.execute(f'PRAGMA table_info("{table}")').fetchall()}
    if column not in existing:
        conn.execute(f"ALTER TABLE {table} ADD COLUMN {column} {definition}")


def _connection_idle(conn: Any) -> bool:
    """True when the caller has no open transaction, so committing here commits only our DDL."""
    in_transaction = getattr(conn, "in_transaction", None)
    if isinstance(in_transaction, bool):  # sqlite3
        return not in_transaction
    info = getattr(conn, "info", None)  # psycopg (LanSharePostgresConnection proxies attributes)
    status = getattr(info, "transaction_status", None)
    return getattr(status, "name", "") == "IDLE"


def _backfill_dm_participants(conn: Any) -> None:
    """One-time fill of ``social_dm_participants`` from existing direct messages (keys are sorted pairs)."""
    if conn.execute("SELECT 1 FROM social_dm_participants LIMIT 1").fetchone() is not None:
        return
    rows = conn.execute(
        "SELECT conversation_key, MAX(id) AS last_id FROM social_messages WHERE conversation_type = 'dm' "
        "GROUP BY conversation_key"
    ).fetchall()
    for row in rows:
        key = str(row["conversation_key"] if hasattr(row, "keys") else row[0])
        last_id = int((row["last_id"] if hasattr(row, "keys") else row[1]) or 0)
        first, sep, second = key[len("dm:"):].partition("|")
        if not key.startswith("dm:") or not sep:
            continue
        for identity in (first, second):
            conn.execute(
                "INSERT INTO social_dm_participants (identity, conversation_key, last_message_id) VALUES (?, ?, ?) "
                "ON CONFLICT (identity, conversation_key) DO NOTHING", (identity, key, last_id),
            )


def ensure_social_schema(conn: Any, *, engine: str | None = None) -> None:
    """Create the social tables on either engine (idempotent).

    The ready flag is only set once the DDL is known to be committed: when the
    caller's connection was idle the DDL is committed here on its own;
    otherwise it rides along in the caller's transaction (which may still roll
    back), so the next call ensures again (cheap ``IF NOT EXISTS``).
    """
    global _SCHEMA_READY
    if _SCHEMA_READY:
        return
    idle = _connection_idle(conn)
    resolved_engine = str(engine or get_configured_db_engine()).strip().lower()
    tables = _table_statements(_id_column(resolved_engine))
    for statement in tables:
        conn.execute(statement)
    for table, column, definition in _ADDED_COLUMNS:
        _add_column_if_missing(conn, resolved_engine, table, column, definition)
    for statement in _INDEX_STATEMENTS:
        conn.execute(statement)
    _backfill_dm_participants(conn)
    if idle:
        conn.commit()
        _SCHEMA_READY = True
