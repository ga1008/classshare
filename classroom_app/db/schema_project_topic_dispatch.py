"""Immutable package references, class-scoped assignments and their history."""

from .connection import get_configured_db_engine


def ensure_project_topic_dispatch_schema(conn):
    identity = ("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
                if get_configured_db_engine() == "postgres" else "INTEGER PRIMARY KEY AUTOINCREMENT")
    conn.execute("""
        CREATE TABLE IF NOT EXISTS project_topic_dispatch_drafts (
            class_offering_id INTEGER NOT NULL REFERENCES class_offerings(id) ON DELETE CASCADE,
            teacher_id INTEGER NOT NULL,
            package_version_id INTEGER NOT NULL REFERENCES project_topic_packages(id) ON DELETE CASCADE,
            revision INTEGER NOT NULL,
            payload_json TEXT,
            updated_at TEXT NOT NULL,
            PRIMARY KEY (class_offering_id,teacher_id,package_version_id)
        )""")
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS project_topic_dispatches (
            id {identity},
            class_offering_id INTEGER NOT NULL REFERENCES class_offerings(id) ON DELETE CASCADE,
            scheme_id INTEGER NOT NULL REFERENCES group_schemes(id),
            package_version_id INTEGER NOT NULL REFERENCES project_topic_packages(id),
            title TEXT NOT NULL,
            mode TEXT NOT NULL CHECK (mode IN ('random','manual')),
            state TEXT NOT NULL CHECK (state IN ('published','archived','withdrawn')),
            revision INTEGER NOT NULL DEFAULT 1,
            teacher_id INTEGER NOT NULL,
            request_id TEXT NOT NULL,
            request_signature TEXT NOT NULL,
            allow_brief INTEGER NOT NULL,
            pool_json TEXT NOT NULL,
            assignment_id TEXT,
            created_at TEXT NOT NULL,
            updated_at TEXT NOT NULL,
            archived_at TEXT,
            UNIQUE (class_offering_id,teacher_id,request_id),
            UNIQUE (id,package_version_id)
        )""")
    conn.execute("""
        CREATE INDEX IF NOT EXISTS idx_project_topic_dispatches_offering
        ON project_topic_dispatches (class_offering_id,id DESC)
    """)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS project_topic_bindings (
            dispatch_id INTEGER NOT NULL,
            package_id INTEGER NOT NULL,
            group_id INTEGER NOT NULL REFERENCES study_groups(id),
            group_name TEXT NOT NULL,
            group_index INTEGER NOT NULL,
            topic_key TEXT NOT NULL,
            PRIMARY KEY (dispatch_id,group_id),
            UNIQUE (dispatch_id,topic_key),
            FOREIGN KEY (dispatch_id,package_id) REFERENCES project_topic_dispatches(id,package_version_id)
                ON DELETE CASCADE,
            FOREIGN KEY (package_id,topic_key) REFERENCES project_topic_items(package_id,topic_key)
        )""")
    conn.execute("""CREATE INDEX IF NOT EXISTS idx_project_topic_bindings_group
                    ON project_topic_bindings (group_id,dispatch_id)""")
    conn.execute("""
        CREATE TABLE IF NOT EXISTS project_topic_dispatch_history (
            dispatch_id INTEGER NOT NULL REFERENCES project_topic_dispatches(id) ON DELETE CASCADE,
            revision INTEGER NOT NULL,
            teacher_id INTEGER NOT NULL,
            action TEXT NOT NULL,
            reason TEXT NOT NULL,
            changes_json TEXT NOT NULL,
            created_at TEXT NOT NULL,
            PRIMARY KEY (dispatch_id,revision)
        )""")
    conn.execute("""
        CREATE TABLE IF NOT EXISTS project_topic_archived_roster (
            dispatch_id INTEGER NOT NULL REFERENCES project_topic_dispatches(id) ON DELETE CASCADE,
            student_id INTEGER NOT NULL,
            student_name TEXT NOT NULL,
            student_number TEXT NOT NULL,
            group_id INTEGER,
            PRIMARY KEY (dispatch_id,student_id)
        )""")
